"""Alternate visual for the article "Performance Is Not Learning" (2026-11-13): a comic strip. Writes visual-comic.svg.

Layout: three panels from one trial (Bastani et al., PNAS 2025). 1: practice with a ChatGPT-style assistant (+48%).
2: the exam, the AI is gone (-17%). 3: the guardrailed tutor that gave hints, not answers (exam drop essentially
gone). Panels appear in turn; in panel 2 the robot fades out. Below: the article's four principles.
"""
from pathlib import Path

from handoff import ROBOT
from people import ANSWER, BUBBLE_PX, QUESTION, STEPS, STUDENT
from pixel import ACCENT, ALERT, INK, SUCCESS, document, sprite, title
from practice_exam_hybrid import BULB

OUT = Path(__file__).resolve().parents[2] / "content/articles/2026-11-13-performance-is-not-learning/visual-comic.svg"
GRAY = "#5d6470"
W, H, TOP = 300, 380, 268
XS = [60, 390, 720]
SHOW = [0, 30, 60]  # % of the loop when each panel appears

STYLE = "".join(
    f"    .p{i} {{ animation: p{i} 6s steps(1) infinite; }}\n    @keyframes p{i} {{ 0% {{ opacity: {1 if i == 0 else 0.12}; }} {p}% {{ opacity: 1; }} }}\n"
    for i, p in enumerate(SHOW) if i
) + """    .gone { animation: gone 6s steps(1) infinite; }
    @keyframes gone { 0% { opacity: 1; } 42% { opacity: 0.15; } }
"""

PANELS = [
    ("1  PRACTICE", "practice score vs. no AI", "+48%", ACCENT),
    ("2  EXAM, NO AI", "exam score vs. no AI", "−17%", ALERT),
    ("3  HINTS ONLY", "exam drop with a tutor", "≈ 0", SUCCESS),
]
PRINCIPLES = [
    "Make the student do the step.",
    "Measure without the tool at least once.",
    "Assess the explanation, not only the artifact.",
    "Build judgment, not trust.",
]


def main():
    body = title("Graded with AI: up.", "Tested without it: down.", "One randomized trial, ~1,000 high school math students (Bastani et al., PNAS 2025)")

    for i, (x, (kicker, label, number, color)) in enumerate(zip(XS, PANELS)):
        cls = f' class="p{i}"' if i else ""
        sy = TOP + 150
        if i == 0:
            scene = (sprite(STUDENT, x + 30, sy) + sprite(ROBOT, x + 174, sy)
                     + sprite(ANSWER, x + 186, TOP + 70, BUBBLE_PX))
        elif i == 1:
            scene = (sprite(STUDENT, x + 30, sy) + f'<g class="gone">{sprite(ROBOT, x + 174, sy)}</g>'
                     + sprite(QUESTION, x + 42, TOP + 70, BUBBLE_PX))
        else:
            scene = (sprite(STUDENT, x + 30, sy) + sprite(ROBOT, x + 174, sy)
                     + sprite(STEPS, x + 42, TOP + 70, BUBBLE_PX) + sprite(BULB, x + 186, TOP + 70, BUBBLE_PX))
        body += f"""
  <g{cls}>
  <rect x="{x + 8}" y="{TOP + 8}" width="{W}" height="{H}" fill="{INK}"/>
  <rect x="{x}" y="{TOP}" width="{W}" height="{H}" fill="#fff" stroke="{INK}" stroke-width="4"/>
  <text x="{x + 20}" y="{TOP + 42}" font-size="22" font-weight="800" fill="{GRAY}" letter-spacing="2">{kicker}</text>
  {scene}
  <text x="{x + W // 2}" y="{TOP + 284}" font-size="22" fill="{GRAY}" text-anchor="middle">{label}</text>
  <text x="{x + W // 2}" y="{TOP + 350}" font-size="60" font-weight="800" fill="{color}" text-anchor="middle">{number}</text>
  </g>"""

    items = "".join(
        f'\n  <text x="100" y="{790 + k * 48}" font-size="28" fill="#d9dce3"><tspan font-weight="800" fill="#fff">{k + 1}.</tspan> {line}</text>'
        for k, line in enumerate(PRINCIPLES)
    )
    body += f"""
  <rect x="68" y="698" width="960" height="310" fill="{ACCENT}"/>
  <rect x="60" y="690" width="960" height="310" fill="{INK}"/>
  <text x="100" y="740" font-size="30" font-weight="800" fill="#fff">Performance isn't learning. Four principles:</text>{items}
  <text x="100" y="978" font-size="22" fill="#9aa1ad">Panel 3: the trial's guardrailed tutor gave hints, not answers.</text>"""

    OUT.write_text(document(body, STYLE, "Generated by scripts/visuals/performance_learning_comic.py. One 6s loop."))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
