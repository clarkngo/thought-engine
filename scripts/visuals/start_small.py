"""Visual for "Start Small. The Ideas Come Later." (2026-11-12): a practice post from Clark's own advice.

Layout: a timeline as a staircase. Four small builds (personal, hobby, work, your next idea) rise left to right.
A student hops up one build at a time; below, the ideas row and the AI-skill bar grow with each step.
No source line (practice post). No takeaway panel.
"""
from pathlib import Path

from people import STUDENT
from pixel import ACCENT, INK, SUCCESS, document, sprite, title

OUT = Path(__file__).resolve().parents[2] / "content/posts/2026-11-12-start-small/visual.svg"
GRAY = "#5d6470"

HOUSE = """
....XX....
...XEEX...
..XEEEEX..
.XEEEEEEX.
XEEEEEEEEX
.XYYYYYYX.
.XYYXXYYX.
.XYYXXYYX.
.XXXXXXXX.
"""
PAD = """
.XXXXXXXX.
XSSSSSSSSX
XSXSSSSRSX
XXXXSSRSRX
XSXSSSSRSX
XSSSXXSSSX
.XXX..XXX.
"""
BAG = """
...XXXX...
...X..X...
XXXXXXXXXX
XDDDDDDDDX
XDDDAADDDX
XDDDDDDDDX
XDDDDDDDDX
XXXXXXXXXX
"""
BULB = """
..XXXX..
.XAAAAX.
XAAYAAAX
XAAAAAAX
XAAAAAAX
.XAAAAX.
..XSSX..
..XSSX..
...XX...
"""

# (label, icon, x, y of card top)
BUILDS = [("Personal", HOUSE, 60), ("Hobby", PAD, 300), ("Work", BAG, 540), ("Your next idea", BULB, 780)]
CARD_W, CARD_H = 220, 130
TOPS = [700, 600, 500, 400]
HOPS = [0, 25, 50, 75]  # % of the loop when the student lands on each card

STYLE = "    .hop { animation: hop 6s steps(1) infinite; }\n    @keyframes hop { " + " ".join(
    f"{p}% {{ transform: translate({BUILDS[i][2] - BUILDS[0][2]}px, {TOPS[i] - TOPS[0]}px); }}" for i, p in enumerate(HOPS)
) + " }\n" + "".join(
    f"    .on{i} {{ animation: on{i} 6s steps(1) infinite; }}\n    @keyframes on{i} {{ 0% {{ opacity: 0.15; }} {p}% {{ opacity: 1; }} }}\n"
    for i, p in enumerate(HOPS)
)


def main():
    body = title("Start small.", "The ideas come later.", "What I tell students, colleagues, and friends who ask where to start with AI")

    for i, (label, icon, x) in enumerate(BUILDS):
        y = TOPS[i]
        last = i == len(BUILDS) - 1
        body += f"""
  <rect x="{x + 8}" y="{y + 8}" width="{CARD_W}" height="{CARD_H}" fill="{ACCENT if last else INK}"/>
  <rect x="{x}" y="{y}" width="{CARD_W}" height="{CARD_H}" fill="#fff" stroke="{INK}" stroke-width="4"/>
  {sprite(icon, x + 16, y + 30, 6)}
  <text x="{x + 84}" y="{y + 76}" font-size="{24 if last else 26}" font-weight="800" fill="{ACCENT if last else INK}">{label.replace('Your next idea', 'Next idea')}</text>"""

    body += f'\n  <g class="hop">{sprite(STUDENT, BUILDS[0][2] + 110, TOPS[0] - 96)}</g>'

    # What grows with each build: ideas and AI skill.
    body += f"""
  <text x="60" y="896" font-size="24" font-weight="800" fill="{GRAY}" letter-spacing="2">IDEAS</text>
  <text x="560" y="896" font-size="24" font-weight="800" fill="{GRAY}" letter-spacing="2">AI SKILL</text>
  <rect x="560" y="914" width="460" height="40" fill="#fff" stroke="{INK}" stroke-width="4"/>"""
    for i in range(4):
        body += f'\n  <g class="on{i}">{sprite(BULB, 60 + i * 76, 908, 5)}</g>'
        body += f'\n  <rect class="on{i}" x="{566 + i * 112}" y="920" width="108" height="28" fill="{SUCCESS}"/>'

    body += f"""
  <text x="60" y="1030" font-size="32" font-weight="800" fill="{INK}">The first project doesn't matter. The tenth one does.</text>"""

    OUT.write_text(document(body, STYLE, "Generated by scripts/visuals/start_small.py. One 6s loop."))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
