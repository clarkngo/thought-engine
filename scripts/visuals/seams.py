"""Visual for the article "The Seams Are the System" (2026-10-21).

Three seams crack in turn (agent handoff, data/code parser, shared credential),
each with its failure, then all three are stitched shut with the fix.
"""
from pathlib import Path

from pixel import ACCENT, ALERT, INK, SUCCESS, document, sprite, title

OUT = Path(__file__).resolve().parents[2] / "content/articles/2026-10-21-the-seams-are-the-system/visual.svg"

CRACK = """
..R..
..R..
.R...
.R...
..R..
...R.
...R.
..R..
.R...
.R...
..R..
...R.
...R.
..R..
"""

# (left block, right block, seam name, failure, fix)
ROWS = [
    ("Agent", "Agent", "Seam 1 · handoff", "~1 in 3 failures (MAST)", "Contract the handoff"),
    ("Data", "Code", "Seam 2 · parser", "Config → code execution", "Treat input as code"),
    ("Cluster", "Cluster", "Seam 3 · credential", "1 key → 2 clusters in 1s", "Scope the credential"),
]
ROW_TOP = [282, 457, 632]
ROW_H = 120
LEFT_X, BLOCK_W, SEAM_W = 60, 200, 80
RIGHT_X = LEFT_X + BLOCK_W + SEAM_W  # 340
TEXT_X = 600
STITCH_AT = 64  # % of the loop when every seam gets stitched


def crack_at(i):
    return 8 + 16 * i


def block(x, y, label):
    return f"""
  <rect x="{x + 8}" y="{y + 8}" width="{BLOCK_W}" height="{ROW_H}" fill="{INK}"/>
  <rect x="{x}" y="{y}" width="{BLOCK_W}" height="{ROW_H}" fill="#fff" stroke="{INK}" stroke-width="4"/>
  <text x="{x + BLOCK_W // 2}" y="{y + 70}" font-size="30" font-weight="700" fill="{INK}" text-anchor="middle">{label}</text>"""


def row(i):
    left, right, name, failure, fix = ROWS[i]
    y = ROW_TOP[i]
    seam_x = LEFT_X + BLOCK_W
    stitches = "".join(
        f'<rect x="{seam_x - 8}" y="{y + 24 + k * 32}" width="{SEAM_W + 16}" height="8" fill="{SUCCESS}"/>'
        for k in range(3)
    )
    return f"""
  <!-- Row {i + 1}: {name} -->
  {block(LEFT_X, y, left)}
  {block(RIGHT_X, y, right)}
  <rect class="tint t{i}" x="{RIGHT_X + 2}" y="{y + 2}" width="{BLOCK_W - 4}" height="{ROW_H - 4}" fill="{ALERT}"/>
  <path class="march" d="M{seam_x + SEAM_W // 2} {y} V{y + ROW_H}" stroke="#c9c5ba" stroke-width="8" fill="none"/>
  <g class="crack c{i}">{sprite(CRACK, seam_x + 20, y + 4)}</g>
  <g class="stitch">{stitches}</g>
  <text x="{TEXT_X}" y="{y + 26}" font-size="22" font-weight="800" fill="#5d6470" letter-spacing="2">{name.upper()}</text>
  <text class="fail f{i}" x="{TEXT_X}" y="{y + 66}" font-size="26" font-weight="700" fill="{ALERT}">✕ {failure}</text>
  <text class="fix" x="{TEXT_X}" y="{y + 104}" font-size="26" font-weight="700" fill="{SUCCESS}">✓ {fix}</text>"""


def main():
    per_row = "".join(
        f"""
    @keyframes c{i} {{ 0% {{ opacity: 0; }} {crack_at(i)}% {{ opacity: 1; }} {crack_at(i) + 2}% {{ opacity: 0.3; }}
      {crack_at(i) + 4}% {{ opacity: 1; }} {STITCH_AT - 2}% {{ opacity: 0; }} }}
    @keyframes f{i} {{ 0% {{ opacity: 0; }} {crack_at(i)}% {{ opacity: 1; }} 94% {{ opacity: 0; }} }}
    @keyframes t{i} {{ 0% {{ opacity: 0; }} {crack_at(i) + 2}% {{ opacity: 0.22; }} {STITCH_AT - 2}% {{ opacity: 0; }} }}
    .c{i} {{ animation-name: c{i}; }} .f{i} {{ animation-name: f{i}; }} .t{i} {{ animation-name: t{i}; }}"""
        for i in range(3)
    )
    style = f"""
    .crack, .fail, .tint {{ opacity: 0; animation-duration: 6s; animation-iteration-count: infinite; animation-timing-function: steps(1); }}
    .stitch, .fix {{ animation: stitch 6s steps(1) infinite; }}
    @keyframes stitch {{ 0% {{ opacity: 0; }} {STITCH_AT}% {{ opacity: 1; }} 94% {{ opacity: 0; }} }}
{per_row}
"""
    panel = f"""
  <rect x="68" y="838" width="960" height="190" fill="{ACCENT}"/>
  <rect x="60" y="830" width="960" height="190" fill="{INK}"/>
  <text x="100" y="878" font-size="30" font-weight="800" fill="#fff">Four rules for the seams</text>
  <g font-size="25" fill="#d9dce3">
    <text x="100" y="934">1. Contract every crossing</text>
    <text x="100" y="982">2. Treat inputs as executable</text>
    <text x="560" y="934">3. Scope authority to the seam</text>
    <text x="560" y="982">4. Verify at the seam</text>
  </g>"""
    body = f"""{title("The seams", "are the system.", "Three boundaries where agentic infrastructure breaks")}
{"".join(row(i) for i in range(3))}
{panel}"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(document(body, style, "Generated by scripts/visuals/seams.py. One 6s loop."))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
