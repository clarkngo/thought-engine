"""Comic-strip version of the "Guardrails Have an Off Switch" visual (2026-11-03): one evening in three panels.

Panels appear in turn: a hint behind the guardrail, still stuck near the deadline, then the click that drops it.
The times are illustrative ("close to the deadline" in Kapoor et al., 2025), not data.
"""
from pathlib import Path

from guardrails import BARRIER
from handoff import ROBOT
from people import ANSWER, CHECK, QUESTION, STUDENT
from pixel import ACCENT, ALERT, INK, document, sprite, title
from practice_exam_hybrid import BULB

OUT = Path(__file__).resolve().parents[2] / "content/posts/2026-11-03-guardrails-have-an-off-switch/visual-comic.svg"
GRAY = "#5d6470"
PANEL_X, PANEL_W, TOP, HEIGHT = [60, 390, 720], 300, 268, 380

# (time, time color, caption lines, student bubble, robot bubble, guardrail up)
PANELS = [
    ("8:00 PM", GRAY, ["Stuck. Asks the tutor.", "Gets a hint."], QUESTION, BULB, True),
    ("11:30 PM", INK, ["Still stuck.", "Deadline is close."], QUESTION, BULB, True),
    ("11:58 PM", ALERT, ["Clicks See Solution.", "Gets the answer."], CHECK, ANSWER, False),
]

STYLE = """
    .p1 { animation: p1 6s steps(1) infinite; }
    @keyframes p1 { 0% { opacity: 0; } 28% { opacity: 1; } 96% { opacity: 0; } }
    .p2 { animation: p2 6s steps(1) infinite; }
    @keyframes p2 { 0% { opacity: 0; } 54% { opacity: 1; } 96% { opacity: 0; } }
    .punch { animation: punch 6s steps(1) infinite; }
    @keyframes punch { 0% { opacity: 0; } 66% { opacity: 1; } 96% { opacity: 0; } }
"""


def panel(i):
    time, color, caption, s_bubble, r_bubble, guard = PANELS[i]
    x = PANEL_X[i]
    sx, rx = x + 30, x + 198
    inner = f"""
    <rect x="{x + 8}" y="{TOP + 8}" width="{PANEL_W}" height="{HEIGHT}" fill="{INK}"/>
    <rect x="{x}" y="{TOP}" width="{PANEL_W}" height="{HEIGHT}" fill="#fff" stroke="{INK}" stroke-width="4"/>
    <text x="{x + 24}" y="{TOP + 46}" font-size="30" font-weight="800" fill="{color}">{time}</text>
    <g class="bob" style="animation-delay:{i * 0.15:.2f}s">{sprite(STUDENT, sx, 420, 6)}</g>
    {sprite(s_bubble, sx + 36, 352, 5)}
    <g class="bob" style="animation-delay:{i * 0.15 + 0.3:.2f}s">{sprite(ROBOT, rx, 420, 6)}</g>
    {sprite(r_bubble, rx + 36 + (6 if r_bubble is BULB else 0), 352 + (4 if r_bubble is BULB else 0), 5)}"""
    if guard:
        inner += f"\n    {sprite(BARRIER, x + 115, 452, 5)}"
    else:
        inner += f"""
    <rect x="{x + 56}" y="{TOP + 250}" width="188" height="40" fill="{ACCENT}"/>
    <text x="{x + 150}" y="{TOP + 277}" font-size="22" font-weight="800" fill="#fff" text-anchor="middle">See Solution</text>"""
    inner += "".join(
        f'\n    <text x="{x + 24}" y="{TOP + 326 + k * 30}" font-size="22" font-weight="700" fill="{INK}">{line}</text>'
        for k, line in enumerate(caption)
    )
    cls = f' class="p{i}"' if i else ""
    return f"\n  <g{cls}>{inner}\n  </g>"


def main():
    body = title("Guardrails have", "an off switch.", "One evening in an intro programming course with an AI tutor")
    body += "".join(panel(i) for i in range(3))
    body += f"""
  <g class="punch">
    <text x="60" y="760" font-size="64" font-weight="800" fill="{ALERT}">Half of 885 students</text>
    <text x="60" y="834" font-size="64" font-weight="800" fill="{INK}">did this at least once.</text>
  </g>
  <text x="60" y="924" font-size="26" fill="{INK}">Most likely to click: lower-performing students, close to the deadline.</text>
  <text x="60" y="1022" font-size="22" fill="{GRAY}">Source: Kapoor, Diaz, MacNeil, Porter &amp; Denny, 2025 (preprint). Times are illustrative.</text>"""

    OUT.write_text(document(body, STYLE, "Generated by scripts/visuals/guardrails_comic.py. One 6s loop."))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
