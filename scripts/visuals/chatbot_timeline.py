"""Timeline visual for "The Chatbot Worked. The Outcomes Didn't Move." (2026-11-02), with a podcast credit.

A student walks four years along a track. The reminder's gain lands at the start (32% to 66%, Table 3, n = 621);
the long-run measures pop in along the way and show no detectable effect. A diagram of the story, not a plotted series.
"""
from pathlib import Path

from handoff import ROBOT
from people import BUBBLE_PX, CHECK, PROFESSOR, QUESTION, STUDENT
from pixel import ACCENT, ALERT, INK, SUCCESS, document, sprite, title

OUT = Path(__file__).resolve().parents[2] / "content/posts/2026-11-02-chatbot-worked-outcomes-didnt-move/visual-timeline.svg"
TRACK_X, TRACK_END, TRACK_Y = 100, 1020, 548
GRAY = "#5d6470"

# (measure, result, center x, appears at % of the loop)
MEASURES = [
    ("GPA", "no detectable effect", 175, 22),
    ("Credits", "no detectable effect", 415, 40),
    ("Persistence", "no detectable effect", 655, 58),
    ("Graduation", "19.0% vs 19.4%", 895, 76),
]

STYLE = """
    .spike { animation: spike 6s steps(1) infinite; }
    @keyframes spike { 0% { opacity: 0; } 6% { opacity: 1; } 96% { opacity: 0; } }
    .walk { animation: walk 6s steps(24) infinite; }
    @keyframes walk { 0% { transform: translateX(0); } 88%, 100% { transform: translateX(840px); } }
""" + "".join(
    f"""    .m{i} {{ animation: m{i} 6s steps(1) infinite; }}
    @keyframes m{i} {{ 0% {{ opacity: 0; }} {at}% {{ opacity: 1; }} 96% {{ opacity: 0; }} }}
"""
    for i, (_, _, _, at) in enumerate(MEASURES)
)


def main():
    body = title("The chatbot worked.", "The outcomes didn't move.", "Randomized trial · 8,708 students · four years · Cal State Northridge")

    body += f"""
  <g class="spike">
    <text x="60" y="366" font-size="104" font-weight="800" fill="{SUCCESS}">32% → 66%</text>
    <text x="60" y="412" font-size="26" font-weight="700" fill="{INK}">registered on time after one reminder*</text>
    <rect x="{TRACK_X - 8}" y="428" width="16" height="{TRACK_Y - 428}" fill="{SUCCESS}"/>
    <g>{sprite(CHECK, 910, 268, BUBBLE_PX)}</g>
  </g>
  <g class="bob">{sprite(ROBOT, 820, 330)}</g>
  <rect x="{TRACK_X}" y="{TRACK_Y}" width="{TRACK_END - TRACK_X}" height="8" fill="{ACCENT}"/>
  <rect x="{TRACK_X}" y="{TRACK_Y + 14}" width="{TRACK_END - TRACK_X}" height="8" fill="#9aa1ad"/>
  <text x="{TRACK_X}" y="600" font-size="22" font-weight="700" fill="{GRAY}">Year 1</text>
  <text x="{TRACK_END}" y="600" font-size="22" font-weight="700" fill="{GRAY}" text-anchor="end">Year 4</text>
  <text x="540" y="600" font-size="22" font-weight="700" fill="{GRAY}" text-anchor="middle">with the chatbot (blue) · without it (gray)</text>
  <g class="walk">{sprite(STUDENT, TRACK_X, TRACK_Y - 72, 6)}</g>"""

    for i, (name, result, cx, _) in enumerate(MEASURES):
        color = ALERT if i == 3 else GRAY
        body += f"""
  <g class="m{i}">
    <text x="{cx}" y="654" font-size="28" font-weight="800" fill="{INK}" text-anchor="middle">{name}</text>
    <text x="{cx}" y="688" font-size="22" font-weight="700" fill="{color}" text-anchor="middle">{result}</text>
  </g>"""

    body += f"""
  <rect x="68" y="728" width="952" height="210" fill="{INK}"/>
  <rect x="60" y="720" width="952" height="210" fill="#fff" stroke="{INK}" stroke-width="4"/>
  <g class="bob" style="animation-delay:0.3s">{sprite(PROFESSOR, 100, 768)}</g>
  {sprite(QUESTION, 210, 736, BUBBLE_PX)}
  <text x="300" y="806" font-size="52" font-weight="800" fill="{INK}">Freed time is not</text>
  <text x="300" y="868" font-size="52" font-weight="800" fill="{ACCENT}">reinvested time.</text>
  <text x="60" y="986" font-size="22" font-weight="700" fill="{INK}">Prompted by Dr. Eric Klein on the Engaged by Design podcast</text>
  <text x="60" y="1022" font-size="22" fill="{GRAY}">*Students not yet enrolled. Source: Mata, Russell &amp; Page, 2026</text>"""

    OUT.write_text(document(body, STYLE, "Generated by scripts/visuals/chatbot_timeline.py. One 6s loop."))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
