"""Visual for "Confidence Is the Variable" (2026-11-10): Lee et al., CHI 2025 (Microsoft Research and CMU).

Layout: a shape that is the idea. A pixel see-saw with a robot (trust in AI) on one end and a student (trust in
yourself) on the other. It tips one way, then the other, on a 6s loop; the line above says what goes with each
side. Two states, steps(1), so it reads as two frames. No takeaway panel.
"""
from pathlib import Path

from handoff import ROBOT
from people import STUDENT
from pixel import ACCENT, ALERT, INK, SUCCESS, document, sprite, title

OUT = Path(__file__).resolve().parents[2] / "content/posts/2026-11-10-confidence-is-the-variable/visual.svg"
GRAY = "#5d6470"
CX, PIVOT_Y = 540, 700
SEG, NSEG, STEP = 80, 10, 12  # plank drawn as 10 stepped segments, 12px rise per segment
LEFT = CX - SEG * NSEG // 2
GROUND = 800

STYLE = """
    .a { animation: a 6s steps(1) infinite; }
    @keyframes a { 0% { opacity: 1; } 50% { opacity: 0; } }
    .b { animation: b 6s steps(1) infinite; }
    @keyframes b { 0% { opacity: 0; } 50% { opacity: 1; } }
"""


def tilt(cls, left_down, line1, line2, color):
    """One state: the stepped plank, both riders, and the line that names the association."""
    sign = 1 if left_down else -1
    ys = [PIVOT_Y + sign * round((NSEG / 2 - 0.5 - i) * STEP) for i in range(NSEG)]
    plank = "".join(
        f'<rect x="{LEFT + i * SEG}" y="{y - 10}" width="{SEG}" height="20" fill="{INK}"/>' for i, y in enumerate(ys)
    )
    return f"""
  <g class="{cls}">
    <text x="{CX}" y="330" font-size="42" font-weight="800" fill="{INK}" text-anchor="middle">{line1}</text>
    <text x="{CX}" y="392" font-size="42" font-weight="800" fill="{color}" text-anchor="middle">{line2}</text>
    {plank}
    {sprite(ROBOT, LEFT + 20, ys[0] - 10 - 96)}
    {sprite(STUDENT, LEFT + SEG * NSEG - 116, ys[-1] - 10 - 96)}
  </g>"""


def main():
    body = title("Trust the tool, think less.", "Trust yourself, think more.", "319 knowledge workers, 936 real uses of AI at work")

    # Fulcrum: a stepped pixel triangle, then the ground.
    for i in range(6):
        w = 24 + i * 24
        body += f'\n  <rect x="{CX - w // 2}" y="{PIVOT_Y + 12 + i * 16}" width="{w}" height="16" fill="{ACCENT}"/>'
    body += f'\n  <rect x="60" y="{GROUND + 4}" width="960" height="12" fill="{INK}"/>'

    body += tilt("a", True, "More trust in AI", "went with less critical thinking", ALERT)
    body += tilt("b", False, "More trust in yourself", "went with more critical thinking", SUCCESS)

    body += f"""
  <text x="{LEFT + 68}" y="{GROUND + 60}" font-size="26" font-weight="800" fill="{INK}" text-anchor="middle">Trust in AI</text>
  <text x="{LEFT + SEG * NSEG - 68}" y="{GROUND + 60}" font-size="26" font-weight="800" fill="{INK}" text-anchor="middle">Trust in yourself</text>
  <text x="60" y="950" font-size="40" font-weight="800" fill="{ACCENT}">Build judgment, not trust in the tool.</text>
  <text x="60" y="1026" font-size="22" fill="{GRAY}">Lee et al., Microsoft Research &amp; Carnegie Mellon, CHI 2025. Survey associations, not causal.</text>"""

    OUT.write_text(document(body, STYLE, "Generated by scripts/visuals/confidence_seesaw.py. One 6s loop."))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
