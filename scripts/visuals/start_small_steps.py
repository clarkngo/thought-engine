"""Alternate visual for "Start Small. The Ideas Come Later." (2026-11-12): you build your own staircase.

Layout: a timeline as a staircase of ten small projects, each column stacked from pixel blocks. A new step appears
every 0.6s and the student climbs onto it; idea bulbs fill the empty space, one per step after the first. The
first project is small, the tenth stands tall. Writes visual-steps.svg. No takeaway panel.
"""
from pathlib import Path

from handoff import CRATE
from people import STUDENT
from pixel import ACCENT, INK, document, sprite, title
from start_small import BULB

OUT = Path(__file__).resolve().parents[2] / "content/posts/2026-11-12-start-small/visual-steps.svg"
GRAY = "#5d6470"
BLOCK = CRATE.replace(".", "Y")  # filled crate: one small project
BW, BH = 52, 44  # block size at px 4
STEP = 56
N = 10
GROUND = 860
X0 = 1020 - N * STEP - 140  # leaves room for the flagpole on the right
POLE_X = 996
TICK = 8  # % of the loop per step

# Idea bulbs, one per step after the first, filling the open space above the low steps.
BULBS = [(70, 330), (190, 310), (310, 340), (110, 440), (240, 420), (370, 460), (70, 560), (200, 540), (330, 600)]


def col_x(i):
    return X0 + i * STEP


def col_top(i):
    return GROUND - (i + 1) * BH


BASE = (col_x(0) + BW // 2 - 48, col_top(0) - 96)  # student's starting top-left
JUMP, LAND = 80, 86  # % of the loop: leap toward the pole, then land at its base and raise the flag

STYLE = (
    "    .climb { animation: climb 6s steps(1) infinite; }\n    @keyframes climb { "
    + " ".join(f"{i * TICK}% {{ transform: translate({i * STEP}px, {col_top(i) - col_top(0)}px); }}" for i in range(N))
    + f" {JUMP}% {{ transform: translate({880 - BASE[0]}px, {col_top(N - 1) - 136 - BASE[1]}px); }}"
    + f" {LAND}% {{ transform: translate({890 - BASE[0]}px, {GROUND - 96 - BASE[1]}px); }} }}\n"
    + f"    .flag {{ animation: flag 6s steps(1) infinite; }}\n    @keyframes flag {{ 0% {{ transform: translateY(0); }} {LAND}% {{ transform: translateY(-440px); }} }}\n"
    + "".join(
        f"    .s{i} {{ animation: s{i} 6s steps(1) infinite; }}\n    @keyframes s{i} {{ 0% {{ opacity: 0; }} {p}% {{ opacity: 1; }} }}\n"
        for i, p in [(i, i * TICK) for i in range(1, N)] + [(f"b{k}", (k + 1) * TICK + 4) for k in range(len(BULBS))]
    )
)


def main():
    body = title("Start small.", "The ideas come later.", "What I tell students, colleagues, and friends who ask where to start with AI")

    body += f'\n  <text x="60" y="296" font-size="24" font-weight="800" fill="{GRAY}" letter-spacing="2">IDEAS</text>'
    for k, (x, y) in enumerate(BULBS):
        body += f'\n  <g class="sb{k}">{sprite(BULB, x, y, 6)}</g>'

    # Ten steps, each a column of small blocks; step i appears at i * TICK% of the loop.
    for i in range(N):
        blocks = "".join(sprite(BLOCK, col_x(i), GROUND - (j + 1) * BH, 4) for j in range(i + 1))
        cls = f' class="s{i}"' if i else ""
        body += f"\n  <g{cls}>{blocks}</g>"
    body += f"""
  <rect x="60" y="{GROUND}" width="960" height="12" fill="{INK}"/>
  <text x="{col_x(0) + BW // 2}" y="{GROUND + 46}" font-size="22" font-weight="800" fill="{INK}" text-anchor="middle">Project 1</text>
  <text x="{col_x(N - 1) + BW // 2}" y="{GROUND + 46}" font-size="22" font-weight="800" fill="{ACCENT}" text-anchor="middle">Project 10</text>
  <rect x="{POLE_X}" y="340" width="8" height="{GROUND - 340}" fill="{INK}"/>
  <rect x="{POLE_X - 6}" y="324" width="20" height="20" fill="{INK}"/>
  <g class="flag">
    <rect x="{POLE_X - 140}" y="790" width="140" height="48" fill="{ACCENT}"/>
    <text x="{POLE_X - 70}" y="822" font-size="22" font-weight="800" fill="#fff" text-anchor="middle">Next idea!</text>
  </g>
  <g class="climb">{sprite(STUDENT, col_x(0) + BW // 2 - 48, col_top(0) - 96)}</g>
  <text x="60" y="1000" font-size="34" font-weight="800" fill="{INK}">The first project doesn't matter. The tenth one does.</text>"""

    OUT.write_text(document(body, STYLE, "Generated by scripts/visuals/start_small_steps.py. One 6s loop."))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
