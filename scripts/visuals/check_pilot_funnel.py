"""Visual for "An AI Check Pilot, Not an AI Detector" (2026-11-19, practice). Writes visual.svg.

Layout: a shape that is the idea, a funnel. Every submission drops into an AI first pass; a few come out
flagged; the instructor turns each flag into a short "explain this line" conversation. Clark's plan for next
term, not a result. No takeaway panel.
"""
from pathlib import Path

from handoff import ROBOT
from people import BUBBLE_PX, CODE, PROFESSOR, QUESTION, STUDENT
from pixel import ACCENT, ALERT, INK, document, sprite, title

OUT = Path(__file__).resolve().parents[2] / "content/posts/2026-11-19-ai-check-pilot-not-detector/visual.svg"
GRAY = "#5d6470"
ICON_PX = 5
ICON_W, ICON_H = 9 * ICON_PX, 10 * ICON_PX
ROW_Y = 292
XS = [90 + i * 98 for i in range(10)]
FLAGGED = [1, 4, 8]
FUNNEL_TOP, FUNNEL_BOT = 374, 600
EXIT_XS = [434, 514, 594]
EXIT_Y = 622

STYLE = """    .flag { animation: flag 6s steps(1) infinite; }
    @keyframes flag { 0% { opacity: 0; } 20% { opacity: 1; } }
    .out { animation: out 6s steps(1) infinite; }
    @keyframes out { 0% { opacity: 0; } 42% { opacity: 1; } }
    .talk { animation: talk 6s steps(1) infinite; }
    @keyframes talk { 0% { opacity: 0; } 62% { opacity: 1; } }
    .scan { animation: scan 6s steps(10) infinite; }
    @keyframes scan { 0% { transform: translateX(0); } 100% { transform: translateX(980px); } }
"""


def flag_box(x, y):
    return f'<rect x="{x - 8}" y="{y - 8}" width="{ICON_W + 16}" height="{ICON_H + 16}" fill="none" stroke="{ALERT}" stroke-width="5"/>'


def main():
    body = title("No AI detectors.", "An AI check pilot instead.", "My plan for next term: AI reads every submission first. I decide who explains.")

    # Every submission, with a scan marker stepping across the row.
    body += f'\n  <text x="90" y="{ROW_Y - 14}" font-size="22" font-weight="800" fill="{GRAY}" letter-spacing="2">EVERY SUBMISSION</text>'
    for i, x in enumerate(XS):
        body += "\n  " + sprite(CODE, x, ROW_Y, ICON_PX)
        if i in FLAGGED:
            body += f'\n  <g class="flag">{flag_box(x, ROW_Y)}</g>'
    body += f'\n  <rect class="scan" x="78" y="{ROW_Y + ICON_H + 10}" width="70" height="6" fill="{ACCENT}"/>'

    # The funnel: the AI first pass.
    body += f"""
  <polygon points="60,{FUNNEL_TOP} 1020,{FUNNEL_TOP} 650,{FUNNEL_BOT} 430,{FUNNEL_BOT}" fill="#fff" stroke="{INK}" stroke-width="4"/>
  <text x="540" y="{FUNNEL_TOP + 44}" font-size="24" font-weight="800" fill="{GRAY}" letter-spacing="2" text-anchor="middle">AI FIRST PASS</text>
  <g class="bob">{sprite(ROBOT, 492, FUNNEL_TOP + 66)}</g>
  <text x="320" y="{FUNNEL_TOP + 84}" font-size="22" fill="{INK}" text-anchor="middle">Reads every one</text>
  <text x="760" y="{FUNNEL_TOP + 84}" font-size="22" fill="{INK}" text-anchor="middle">Flags what needs me</text>"""

    # What comes out: the flagged few.
    body += '\n  <g class="out">'
    for x in EXIT_XS:
        body += sprite(CODE, x, EXIT_Y, ICON_PX) + flag_box(x, EXIT_Y)
    body += f'<text x="674" y="{EXIT_Y + 34}" font-size="24" font-weight="800" fill="{ALERT}">Flagged</text></g>'

    # The human part: a short conversation.
    sy = 756
    body += f"""
  {sprite(PROFESSOR, 120, sy)}
  {sprite(STUDENT, 300, sy)}
  <g class="talk">{sprite(QUESTION, 142, sy - 72, BUBBLE_PX)}
  <text x="460" y="{sy + 34}" font-size="30" font-weight="800" fill="{INK}">"Walk me through this line."</text>
  <text x="460" y="{sy + 74}" font-size="24" fill="{GRAY}">A two-minute conversation, not a verdict.</text></g>
  <text x="60" y="920" font-size="34" font-weight="800" fill="{INK}">The AI flags. I decide.</text>
  <text x="60" y="968" font-size="34" font-weight="800" fill="{ACCENT}">My attention goes where it counts.</text>
  <text x="60" y="1030" font-size="22" fill="{GRAY}">A plan for next term, not a result yet.</text>"""

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(document(body, STYLE, "Generated by scripts/visuals/check_pilot_funnel.py. One 6s loop."))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
