"""Third visual for "67% Less Escalation" (2026-11-17): a comic strip. Writes visual-comic.svg.

Layout: three panels of behavior. 1: rehearse with an AI that pushes back. 2: feedback on strategy. 3: the real
conflict with a person, no AI in the room. Panels appear in turn. Below: the result vs. a lecture group
(Shaikh et al., CHI 2024). No takeaway panel.
"""
from pathlib import Path

from handoff import ROBOT
from people import BUBBLE_PX, CHECK, STUDENT
from pixel import ACCENT, INK, SUCCESS, document, sprite, title
from practice_exam_hybrid import BULB
from sim_sprites import BOLT, HEART

OUT = Path(__file__).resolve().parents[2] / "content/posts/2026-11-17-rehearse-the-conflict/visual-comic.svg"
GRAY = "#5d6470"
W, H, TOP = 300, 390, 268
XS = [60, 390, 720]
SHOW = [0, 30, 60]

# A coworker: same build as the student, different hair and shirt.
COWORKER = STUDENT.replace("H", "D").replace("B", "R")

STYLE = "".join(
    f"    .p{i} {{ animation: p{i} 6s steps(1) infinite; }}\n    @keyframes p{i} {{ 0% {{ opacity: 0.12; }} {p}% {{ opacity: 1; }} }}\n"
    for i, p in enumerate(SHOW) if i
)

PANELS = [
    ("1  REHEARSE", "The AI pushes back."),
    ("2  FEEDBACK", "Which strategy, when."),
    ("3  THE REAL ONE", "No AI in the room."),
]


def scene(i, x):
    sy = TOP + 170
    you = sprite(STUDENT, x + 30, sy)
    if i == 0:
        return you + sprite(ROBOT, x + 174, sy) + f'<g class="bob">{sprite(BOLT, x + 202, TOP + 80, 5)}</g>'
    if i == 1:
        return you + sprite(ROBOT, x + 174, sy) + sprite(CHECK, x + 186, TOP + 74, BUBBLE_PX) + sprite(BULB, x + 54, TOP + 80, BUBBLE_PX)
    return (you + sprite(COWORKER, x + 174, sy) + sprite(BOLT, x + 202, TOP + 80, 5)
            + f'<g class="bob">{sprite(HEART, x + 58, TOP + 92, 6)}</g>')


def main():
    body = title("Rehearse it with an AI.", "Then have it for real.", "Stanford's Rehearsal study: 40 participants, AI practice vs. a lecture")

    for i, (x, (kicker, caption)) in enumerate(zip(XS, PANELS)):
        cls = f' class="p{i}"' if i else ""
        last = i == 2
        body += f"""
  <g{cls}>
  <rect x="{x + 8}" y="{TOP + 8}" width="{W}" height="{H}" fill="{ACCENT if last else INK}"/>
  <rect x="{x}" y="{TOP}" width="{W}" height="{H}" fill="#fff" stroke="{INK}" stroke-width="4"/>
  <text x="{x + 20}" y="{TOP + 42}" font-size="22" font-weight="800" fill="{ACCENT if last else GRAY}" letter-spacing="2">{kicker}</text>
  {scene(i, x)}
  <text x="{x + W // 2}" y="{TOP + 330}" font-size="24" font-weight="800" fill="{INK}" text-anchor="middle">{caption}</text>
  </g>"""

    body += f"""
  <text x="60" y="728" font-size="24" font-weight="800" fill="{GRAY}" letter-spacing="2">IN THE REAL CONFLICT, VS. A LECTURE GROUP</text>
  <text x="52" y="850" font-size="120" font-weight="800" fill="{ACCENT}" letter-spacing="-4">−67%</text>
  <text x="60" y="896" font-size="28" font-weight="800" fill="{INK}">escalating tactics</text>
  <text x="560" y="850" font-size="120" font-weight="800" fill="{SUCCESS}" letter-spacing="-4">2×</text>
  <text x="568" y="896" font-size="28" font-weight="800" fill="{INK}">cooperative tactics</text>
  <text x="60" y="966" font-size="34" font-weight="800" fill="{INK}">Make the mistakes where they're free.</text>
  <text x="60" y="1018" font-size="22" fill="{GRAY}">Shaikh et al., CHI 2024 (Stanford). Lab study; short-term effects.</text>"""

    OUT.write_text(document(body, STYLE, "Generated by scripts/visuals/rehearsal_comic.py. One 6s loop."))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
