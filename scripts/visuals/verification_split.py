"""Split-screen version of the "Teach Verification, Not Syntax" visual (2026-11-04): Fowles et al. (2026), arXiv:2605.21374.

Left: grade the artifact. AI or student, the same code reaches the grader, who can't tell who wrote it.
Right: grade the explanation. A short oral review: the instructor asks, the student explains, the instructor checks.
Below: the course result. No takeaway panel.
"""
from pathlib import Path

from handoff import ROBOT
from people import CHECK, CODE, PROFESSOR, QUESTION, STEPS, STUDENT
from pixel import ACCENT, ALERT, INK, SUCCESS, document, pixel_arrow, sprite, title

OUT = Path(__file__).resolve().parents[2] / "content/posts/2026-11-04-teach-verification-not-syntax/visual-split.svg"
GRAY = "#5d6470"
ACTOR_PX, BUBBLE_PX = 7, 5

STYLE = """
    .ask { animation: ask 6s steps(1) infinite; }
    @keyframes ask { 0% { opacity: 1; } 33% { opacity: 0; } 100% { opacity: 0; } }
    .explain { animation: explain 6s steps(1) infinite; }
    @keyframes explain { 0% { opacity: 0; } 33% { opacity: 1; } 66% { opacity: 0; } }
    .verified { animation: verified 6s steps(1) infinite; }
    @keyframes verified { 0% { opacity: 0; } 66% { opacity: 1; } 96% { opacity: 0; } }
    .who { animation: who 6s steps(1) infinite; }
    @keyframes who { 0% { opacity: 0; } 25% { opacity: 1; } 96% { opacity: 0; } }
    .swap-a { animation: swap-a 6s steps(1) infinite; }
    @keyframes swap-a { 0% { opacity: 1; } 50% { opacity: 0; } 100% { opacity: 0; } }
    .swap-b { animation: swap-b 6s steps(1) infinite; }
    @keyframes swap-b { 0% { opacity: 0; } 50% { opacity: 1; } 100% { opacity: 1; } }
"""


def panel(x, heading, color):
    return f"""
  <rect x="{x + 8}" y="288" width="452" height="372" fill="{INK}"/>
  <rect x="{x}" y="280" width="452" height="372" fill="#fff" stroke="{INK}" stroke-width="4"/>
  <text x="{x + 24}" y="324" font-size="24" font-weight="800" fill="{color}" letter-spacing="2">{heading}</text>"""


def main():
    body = title("Teach verification,", "not syntax.", "Intro CS course with AI allowed and weekly oral code reviews")

    # Left: the artifact. The author swaps between robot and student; the grader can't tell.
    body += panel(60, "GRADE THE ARTIFACT", ALERT)
    body += f"""
  <g class="swap-a"><g class="bob">{sprite(ROBOT, 90, 420, ACTOR_PX)}</g></g>
  <g class="swap-b"><g class="bob">{sprite(STUDENT, 90, 420, ACTOR_PX)}</g></g>
  {sprite(CODE, 150, 352, BUBBLE_PX)}
  {pixel_arrow(196, 318, 466)}
  <g class="bob" style="animation-delay:0.3s">{sprite(PROFESSOR, 384, 420, ACTOR_PX)}</g>
  <g class="who">{sprite(QUESTION, 444, 352, BUBBLE_PX)}</g>
  <text x="84" y="580" font-size="24" font-weight="700" fill="{INK}">Same code, AI or student.</text>
  <text x="84" y="614" font-size="24" font-weight="700" fill="{INK}">The grade can't tell them apart.</text>"""

    # Right: the explanation. Ask, explain, verify.
    body += panel(568, "GRADE THE EXPLANATION", SUCCESS)
    body += f"""
  <g class="bob">{sprite(STUDENT, 610, 420, ACTOR_PX)}</g>
  <g class="explain">{sprite(STEPS, 670, 352, BUBBLE_PX)}</g>
  <g class="bob" style="animation-delay:0.3s">{sprite(PROFESSOR, 880, 420, ACTOR_PX)}</g>
  <g class="ask">{sprite(QUESTION, 940, 352, BUBBLE_PX)}</g>
  <g class="verified">{sprite(CHECK, 940, 352, BUBBLE_PX)}</g>
  <text x="592" y="580" font-size="24" font-weight="700" fill="{INK}">Five minutes: explain, defend.</text>
  <text x="592" y="614" font-size="24" font-weight="700" fill="{INK}">Evidence of learning.</text>"""

    # The course result.
    body += f"""
  <text x="60" y="728" font-size="24" font-weight="800" fill="{GRAY}" letter-spacing="2">WHAT HAPPENED IN THE COURSE</text>
  <text x="60" y="776" font-size="26" font-weight="700" fill="{INK}">AI use (pasted code)</text>
  <text x="60" y="842" font-size="58" font-weight="800" fill="{ACCENT}">went up ↑</text>
  <text x="568" y="776" font-size="26" font-weight="700" fill="{INK}">Exam averages</text>
  <text x="568" y="842" font-size="58" font-weight="800" fill="{SUCCESS}">held steady →</text>
  <text x="60" y="934" font-size="32" font-weight="800" fill="{INK}">Not ban AI. Not allow AI. Move the assessment.</text>
  <text x="60" y="1026" font-size="22" fill="{GRAY}">Source: Fowles et al., 2026 (preprint, one course); no significant change in exam averages</text>"""

    OUT.write_text(document(body, STYLE, "Generated by scripts/visuals/verification_split.py. One 6s loop."))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
