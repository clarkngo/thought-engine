"""Visual for the quick take "67% Less Escalation" (2026-11-17). Source: Shaikh et al., CHI 2024 (Rehearsal).

Layout: one giant number, plus a comparison card that flips between the lecture group and the Rehearsal group.
Six bolts become two (67% fewer escalating tactics); two hearts become four (cooperative tactics doubled).
Icons illustrate the reported averages, not individual counts. No takeaway panel.
"""
from pathlib import Path

from handoff import ROBOT
from people import STUDENT
from pixel import ACCENT, ALERT, INK, SUCCESS, document, sprite, title
from sim_sprites import BOLT, HEART

OUT = Path(__file__).resolve().parents[2] / "content/posts/2026-11-17-rehearse-the-conflict/visual.svg"
GRAY = "#5d6470"
SLOT, ICON_X = 92, 330

STYLE = """    .a { animation: a 6s steps(1) infinite; }
    @keyframes a { 0% { opacity: 1; } 50% { opacity: 0; } }
    .b { animation: b 6s steps(1) infinite; }
    @keyframes b { 0% { opacity: 0; } 50% { opacity: 1; } }
"""


def main():
    body = title("Practiced with an AI opponent.", "Then the real conflict.", "Stanford's Rehearsal study: AI practice vs. a lecture, 40 participants")

    # Giant number and the scene.
    body += f"""
  <text x="52" y="500" font-size="230" font-weight="800" fill="{ACCENT}" letter-spacing="-8">67%</text>
  <text x="60" y="566" font-size="34" font-weight="800" fill="{INK}">fewer escalating tactics</text>
  <text x="60" y="612" font-size="34" font-weight="800" fill="{SUCCESS}">2× the cooperative ones</text>
  <g class="bob">{sprite(BOLT, 912, 296, 5)}</g>
  {sprite(HEART, 690, 310, 5)}
  {sprite(STUDENT, 660, 380)}
  {sprite(ROBOT, 880, 380)}
  <text x="708" y="508" font-size="22" font-weight="800" fill="{INK}" text-anchor="middle">You</text>
  <text x="928" y="508" font-size="22" font-weight="800" fill="{INK}" text-anchor="middle">AI opponent</text>"""

    # Comparison card: lecture group (first half of the loop) vs. Rehearsal group (second half).
    body += f"""
  <rect x="68" y="668" width="952" height="236" fill="{ACCENT}"/>
  <rect x="60" y="660" width="952" height="236" fill="#fff" stroke="{INK}" stroke-width="4"/>
  <text class="a" x="84" y="706" font-size="24" font-weight="800" fill="{GRAY}" letter-spacing="2">LECTURE GROUP</text>
  <text class="b" x="84" y="706" font-size="24" font-weight="800" fill="{ACCENT}" letter-spacing="2">REHEARSAL GROUP</text>
  <text x="84" y="774" font-size="28" font-weight="800" fill="{INK}">Escalating</text>
  <text x="84" y="860" font-size="28" font-weight="800" fill="{INK}">Cooperative</text>"""
    for i in range(6):
        x = ICON_X + i * SLOT
        body += f'\n  <rect x="{x - 6}" y="730" width="52" height="62" fill="#efece4"/>'
        bolt = sprite(BOLT, x + 1, 736, 5)
        body += f'\n  <g class="a">{bolt}</g>' if i >= 2 else f"\n  {bolt}"
        body += f'\n  <rect x="{x - 6}" y="818" width="52" height="54" fill="#efece4"/>'
        heart = sprite(HEART, x + 1, 828, 5)
        if i < 2:
            body += f"\n  {heart}"
        elif i < 4:
            body += f'\n  <g class="b">{heart}</g>'

    body += f"""
  <text x="60" y="954" font-size="34" font-weight="800" fill="{INK}">Practice the hard conversation before it's real.</text>
  <text x="60" y="1004" font-size="22" fill="{GRAY}">Shaikh et al., CHI 2024 (Stanford). Measured in a real conflict after training.</text>
  <text x="60" y="1036" font-size="22" fill="{GRAY}">Icons illustrate the average change, not individual counts.</text>"""

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(document(body, STYLE, "Generated by scripts/visuals/rehearsal.py. One 6s loop."))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
