"""Visual for the article "Performance Is Not Learning" (2026-11-13). Pattern from Bastani et al., PNAS 2025.

Layout: a timeline. Two stepped lines across practice and the exam: the group with ChatGPT-style help sits above
the no-AI group during practice (+48%), then drops below it when the AI is removed for the exam (-17%). A student
and robot ride the AI line; at the exam the robot vanishes and the student drops. Not to scale. No panel.
"""
from pathlib import Path

from handoff import ROBOT
from people import STUDENT
from pixel import ACCENT, ALERT, INK, document, sprite, title

OUT = Path(__file__).resolve().parents[2] / "content/articles/2026-11-13-performance-is-not-learning/visual.svg"
GRAY = "#5d6470"
STEEL = "#9aa1ad"
X0, SPLIT, X1 = 100, 760, 1000
AI_Y, NOAI_Y, EXAM_Y = 450, 570, 692  # line tops: AI in practice, no-AI, AI on the exam

# Student path along the AI line: (keyframe %, dx, dy). Holds each spot, then drops at the exam.
PATH = [(0, 0, 0), (16, 140, 0), (32, 280, 0), (48, 420, 0), (64, 540, 0), (80, 720, EXAM_Y - AI_Y)]


def keyframes(name, extra_last=""):
    frames = " ".join(f"{p}% {{ transform: translate({dx}px, {dy}px); }}" for p, dx, dy in PATH)
    return f"    .{name} {{ animation: {name} 6s steps(1) infinite; }}\n    @keyframes {name} {{ {frames} {extra_last}}}\n"


STYLE = keyframes("ride") + """    .bot { animation: bot 6s steps(1) infinite; }
    @keyframes bot { 0% { transform: translate(0, 0); opacity: 1; } 16% { transform: translate(140px, 0); }
      32% { transform: translate(280px, 0); } 48% { transform: translate(420px, 0); }
      64% { transform: translate(540px, 0); opacity: 1; } 80% { opacity: 0; } }
    .drop { animation: drop 6s steps(1) infinite; }
    @keyframes drop { 0% { opacity: 0; } 80% { opacity: 1; } }
"""


def main():
    body = title("Practice scores went up.", "Exam scores went down.", "One randomized trial, two groups, AI removed for the exam")

    # Zones.
    body += f"""
  <text x="{X0}" y="320" font-size="24" font-weight="800" fill="{GRAY}" letter-spacing="2">PRACTICE: WITH AI</text>
  <text x="{SPLIT + 30}" y="320" font-size="24" font-weight="800" fill="{GRAY}" letter-spacing="2">EXAM: NO AI</text>
  <path d="M{SPLIT} 290 V780" stroke="{GRAY}" stroke-width="4" stroke-dasharray="12 10"/>
  <rect x="{X0}" y="780" width="{X1 - X0}" height="8" fill="{INK}"/>"""

    # No-AI line runs straight through; the AI line sits above it, then drops below at the exam.
    body += f"""
  <rect x="{X0}" y="{NOAI_Y}" width="{X1 - X0}" height="12" fill="{STEEL}"/>
  <text x="{X0}" y="{NOAI_Y + 46}" font-size="24" font-weight="800" fill="{GRAY}">No AI</text>
  <rect x="{X0}" y="{AI_Y}" width="{SPLIT - X0}" height="12" fill="{ACCENT}"/>
  <text x="{X0}" y="{AI_Y + 46}" font-size="24" font-weight="800" fill="{ACCENT}">ChatGPT-style help</text>
  <text x="430" y="{AI_Y + 50}" font-size="44" font-weight="800" fill="{ACCENT}">+48%</text>
  <rect x="{SPLIT - 12}" y="{AI_Y}" width="12" height="{EXAM_Y - AI_Y + 12}" fill="{ALERT}"/>
  <rect x="{SPLIT}" y="{EXAM_Y}" width="{X1 - SPLIT}" height="12" fill="{ALERT}"/>
  <g class="drop"><text x="{SPLIT + 30}" y="{EXAM_Y + 60}" font-size="44" font-weight="800" fill="{ALERT}">−17%</text></g>"""

    # Riders: robot beside the student until the exam.
    body += f"""
  <g class="bot">{sprite(ROBOT, X0 + 10, AI_Y - 72, 6)}</g>
  <g class="ride">{sprite(STUDENT, X0 + 90, AI_Y - 96)}</g>"""

    body += f"""
  <text x="60" y="872" font-size="38" font-weight="800" fill="{INK}">Performance: what students do with help.</text>
  <text x="60" y="924" font-size="38" font-weight="800" fill="{ACCENT}">Learning: what remains without it.</text>
  <text x="60" y="996" font-size="22" fill="{GRAY}">Bastani et al., PNAS 2025: ~1,000 high school math students, vs. a no-AI group.</text>
  <text x="60" y="1028" font-size="22" fill="{GRAY}">Not to scale.</text>"""

    OUT.write_text(document(body, STYLE, "Generated by scripts/visuals/performance_learning.py. One 6s loop."))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
