"""Visual for "The AI Honesty Penalty" (2026-11-23). Writes visual.svg.

Layout: a scene. One worker hands in one piece of work with an "AI-assisted" tag. Two evaluators judge the
identical work: one who rarely uses AI (red X, "lazy?"), one who uses AI daily (green check). Sources:
Reif, Larrick & Soll, PNAS 2025 (evaluator's own AI use moderates the penalty); Atlassian Teamwork Lab 2026
(identical work, 24 points less likely to be recommended). No takeaway panel.
"""
from pathlib import Path

from handoff import ROBOT
from people import BUBBLE_PX, CHECK, PROFESSOR, STUDENT
from pixel import ACCENT, ALERT, INK, SUCCESS, document, sprite, title

OUT = Path(__file__).resolve().parents[2] / "content/posts/2026-11-23-the-ai-honesty-penalty/visual.svg"
GRAY = "#5d6470"

CROSS = """
.XXXXXXX.
XYYYYYYYX
XYRYYYRYX
XYYRYRYYX
XYYYRYYYX
XYYRYRYYX
XYRYYYRYX
.XXXXXXX.
....XX...
....X....
"""

# Same build as the professor, darker hair and a blue tie: the evaluator who uses AI daily.
EVAL_AI = PROFESSOR.replace("S", "D").replace("R", "E")

STYLE = """    .tag { animation: tag 6s steps(1) infinite; }
    @keyframes tag { 0% { opacity: 0; } 15% { opacity: 1; } }
    .left { animation: left 6s steps(1) infinite; }
    @keyframes left { 0% { opacity: 0; } 40% { opacity: 1; } }
    .right { animation: right 6s steps(1) infinite; }
    @keyframes right { 0% { opacity: 0; } 62% { opacity: 1; } }
"""


def doc_card(x, y):
    lines = "".join(f'<rect x="{x + 28}" y="{y + 36 + i * 26}" width="{w}" height="10" fill="#c9ccd3"/>' for i, w in enumerate([240, 200, 228]))
    return f"""
  <rect x="{x + 8}" y="{y + 8}" width="300" height="150" fill="{INK}"/>
  <rect x="{x}" y="{y}" width="300" height="150" fill="#fff" stroke="{INK}" stroke-width="4"/>{lines}
  <g class="tag"><rect x="{x + 28}" y="{y + 108}" width="160" height="30" fill="{ACCENT}"/>
  <text x="{x + 108}" y="{y + 130}" font-size="20" font-weight="800" fill="#fff" text-anchor="middle">AI-ASSISTED</text></g>"""


def panel(x, kicker, who, verdict_sprite, verdict, color, detail, cls, extra=""):
    y = 520
    return f"""
  <rect x="{x + 8}" y="{y + 8}" width="460" height="290" fill="{INK}"/>
  <rect x="{x}" y="{y}" width="460" height="290" fill="#fff" stroke="{INK}" stroke-width="4"/>
  <text x="{x + 24}" y="{y + 42}" font-size="22" font-weight="800" fill="{GRAY}" letter-spacing="2">{kicker}</text>
  {sprite(who, x + 40, y + 110)}{extra}
  <g class="{cls}">{sprite(verdict_sprite, x + 60, y + 54, BUBBLE_PX)}
  <text x="{x + 200}" y="{y + 160}" font-size="44" font-weight="800" fill="{color}">{verdict}</text>
  <text x="{x + 200}" y="{y + 200}" font-size="22" fill="{INK}">{detail[0]}</text>
  <text x="{x + 200}" y="{y + 230}" font-size="22" fill="{INK}">{detail[1]}</text></g>"""


def main():
    body = title("Same work. Same disclosure.", "It depends who is judging.", "Disclosing AI use costs you most with people who don't use it")

    # The worker and the identical piece of work.
    body += f"\n  {sprite(STUDENT, 250, 330)}" + doc_card(400, 300)
    body += f'\n  <text x="790" y="390" font-size="24" font-weight="800" fill="{INK}">Identical work</text>'

    body += panel(60, "RARELY USES AI", PROFESSOR, CROSS, "Lazy?", ALERT,
                  ("Rated lazier.", "Picks the non-AI one."), "left")
    body += panel(560, "USES AI DAILY", EVAL_AI, CHECK, "Fine.", SUCCESS,
                  ("No laziness penalty.", "Picks the daily AI user."), "right",
                  extra=sprite(ROBOT, 560 + 120, 520 + 166, 4))

    body += f"""
  <text x="60" y="878" font-size="30" font-weight="800" fill="{INK}">Identical work, AI disclosed:</text>
  <text x="60" y="924" font-size="30" font-weight="800" fill="{ALERT}">24 points less likely to be recommended.</text>
  <text x="60" y="990" font-size="22" fill="{GRAY}">Reif, Larrick &amp; Soll, PNAS 2025 (Duke): 4 experiments, 4,439 people.</text>
  <text x="60" y="1024" font-size="22" fill="{GRAY}">Atlassian Teamwork Lab 2026: 961 U.S. knowledge workers.</text>"""

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(document(body, STYLE, "Generated by scripts/visuals/honesty_penalty.py. One 6s loop."))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
