"""Stage-flow version of "The Bottleneck Moved" (2026-11-05), from the before/after framing in Clark's staff briefing.

Two process rows. A red highlight and an hourglass mark the bottleneck: on "Write & build" in the before row,
then it jumps to "Keep consistent" in the AI row. No takeaway panel.
"""
from pathlib import Path

from handoff import ROBOT
from people import CHECK, PROFESSOR, QUESTION, STEPS
from pixel import ACCENT, ALERT, INK, SUCCESS, document, sprite, title

OUT = Path(__file__).resolve().parents[2] / "content/posts/2026-11-05-the-bottleneck-moved/visual-flow.svg"
GRAY = "#5d6470"
BOX_X, BOX_W, BOX_H = [60, 306, 552, 798], 222, 150

HOURGLASS = """
XXXXXXX
.XAAAX.
..XAX..
...X...
..XAX..
.XAAAX.
XXXXXXX
"""

# (label, sprite, caption) per stage; the bottleneck index per row.
ROWS = [
    ("BEFORE: LIMITED BY WRITING", 316, 1, "before", [
        ("Decide", PROFESSOR, "outline the course"),
        ("Write &amp; build", STEPS, "weeks per module"),
        ("Review", QUESTION, "notes, weeks later"),
        ("Launch", CHECK, "changes wait a term"),
    ]),
    ("NOW: LIMITED BY DECISIONS AND CONSISTENCY", 576, 2, "now", [
        ("Decide", PROFESSOR, "only faculty can"),
        ("AI drafts", ROBOT, "minutes"),
        ("Keep consistent", PROFESSOR, "syllabus · site · LMS"),
        ("Launch", CHECK, "fixes live same day"),
    ]),
]

STYLE = """
    .before { animation: before 6s steps(1) infinite; }
    @keyframes before { 0% { opacity: 1; } 48% { opacity: 0; } 96% { opacity: 1; } }
    .now { animation: now 6s steps(1) infinite; }
    @keyframes now { 0% { opacity: 0; } 50% { opacity: 1; } 96% { opacity: 0; } }
"""


def row(label, top, hot, cls, stages):
    out = f'\n  <text x="60" y="{top - 16}" font-size="22" font-weight="800" fill="{GRAY}" letter-spacing="2">{label}</text>'
    for i, (name, art, caption) in enumerate(stages):
        x = BOX_X[i]
        cx = x + BOX_W // 2
        is_sprite_person = art in (PROFESSOR, ROBOT)
        px = 5 if is_sprite_person else 6
        w = (12 if is_sprite_person else 9) * px
        out += f"""
  <rect x="{x + 8}" y="{top + 8}" width="{BOX_W}" height="{BOX_H}" fill="{INK}"/>
  <rect x="{x}" y="{top}" width="{BOX_W}" height="{BOX_H}" fill="#fff" stroke="{INK}" stroke-width="4"/>"""
        if i == hot:
            out += f"""
  <g class="{cls}">
    <rect x="{x}" y="{top}" width="{BOX_W}" height="{BOX_H}" fill="#fde8e1" stroke="{ALERT}" stroke-width="6"/>
    {sprite(HOURGLASS, x + BOX_W - 22, top - 20, 6)}
  </g>"""
        out += f"""
  <text x="{cx}" y="{top + 36}" font-size="25" font-weight="800" fill="{INK}" text-anchor="middle">{name}</text>
  <g class="bob" style="animation-delay:{i * 0.15:.2f}s">{sprite(art, cx - w // 2, top + 48, px)}</g>
  <text x="{cx}" y="{top + 134}" font-size="22" font-weight="700" fill="{GRAY}" text-anchor="middle">{caption}</text>"""
        if i < 3:
            ax = x + BOX_W + 6
            out += f'\n  <path d="M{ax} {top + 63} L{ax + 14} {top + 75} L{ax} {top + 87} Z" fill="{INK}"/>'
    return out


def main():
    body = title("Drafting got fast.", "The bottleneck moved.", "Building a course, before and after an AI build partner")
    body += "".join(row(*r) for r in ROWS)
    body += f"""
  <text x="60" y="842" font-size="44" font-weight="800" fill="{INK}">Building is no longer the bottleneck.</text>
  <text x="60" y="900" font-size="44" font-weight="800" fill="{ACCENT}">Deciding and staying consistent are.</text>
  <text x="60" y="1026" font-size="22" fill="{GRAY}">From one course build, Aug–Oct 2026</text>"""

    OUT.write_text(document(body, STYLE, "Generated by scripts/visuals/bottleneck_flow.py. One 6s loop."))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
