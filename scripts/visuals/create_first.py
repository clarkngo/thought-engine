"""Visual for "Create Comes First" (2026-10-29): a Create-first grading cycle (Bloom's, reordered for AI).

Top (pixel): four stage cards. The robot creates; then the student evaluates, explains, and refines
by hand with the robot gone. A highlight steps from card to card, 1.5s each (negative delays, so the loop is seamless from frame 0).
Bottom (flat): Create is 20% of the grade; Evaluate, Analyze and Understand & Refine are 80%.
"""
from pathlib import Path

from handoff import ROBOT
from people import CHECK, CODE, STEPS, STUDENT
from pixel import ACCENT, INK, divider, flat_panel, hybrid_document, sprite, title

OUT = Path(__file__).resolve().parents[2] / "content/posts/2026-10-29-create-comes-first/visual-hybrid.svg"
SPRITE_PX, BUBBLE_PX = 6, 5
CARD_W, CARD_X = 216, [60, 308, 556, 804]

# (label, actor, bubble)
STAGES = [
    ("1 · Create", ROBOT, CODE),
    ("2 · Evaluate", STUDENT, CHECK),
    ("3 · Analyze", STUDENT, STEPS),
    ("4 · Refine", STUDENT, CODE),
]

STYLE = """
    .on { animation: on 6s steps(1) infinite both; }
    @keyframes on { 0% { opacity: 1; } 25% { opacity: 0; } 100% { opacity: 0; } }
    .bar { transform-box: fill-box; transform-origin: left center; animation: grow 6s linear infinite both; }
    @keyframes grow { 0% { transform: scaleX(0); } 15%, 92% { transform: scaleX(1); } 98%, 100% { transform: scaleX(0); } }
    .num { animation: num 6s linear infinite both; }
    @keyframes num { 0%, 12% { opacity: 0; } 18%, 92% { opacity: 1; } 96%, 100% { opacity: 0; } }
"""


def card(i):
    label, actor, bubble = STAGES[i]
    x = CARD_X[i]
    cx = x + CARD_W // 2
    return f"""
  <g>
    <rect x="{x + 8}" y="278" width="{CARD_W}" height="220" fill="{INK}"/>
    <rect x="{x}" y="270" width="{CARD_W}" height="220" fill="#fff" stroke="{INK}" stroke-width="4"/>
    <rect class="on" style="animation-delay:{i * 1.5 - 6:.1f}s" x="{x + 6}" y="276" width="{CARD_W - 12}" height="208" fill="#e7ecfd"/>
    <g class="bob" style="animation-delay:{i * 0.15:.2f}s">{sprite(actor, cx - 36, 344, SPRITE_PX)}</g>
    {sprite(bubble, cx + 22, 290, BUBBLE_PX)}
    <text x="{cx}" y="458" font-size="24" font-weight="700" fill="{INK}" text-anchor="middle">{label}</text>
  </g>"""


def main():
    top = title("Bloom's puts Create on top.", "My course starts there.",
                "AI writes the first draft · the student does the rest")
    top += "".join(card(i) for i in range(4))

    create_w, rest_w = 192, 768  # 20% and 80% of 960
    flat = divider("HOW THE GRADE IS SPLIT")
    flat += f"""
  <text x="60" y="604" font-size="22" font-weight="700" fill="#5d6470">AI creates</text>
  <text x="{60 + create_w + 16}" y="604" font-size="22" font-weight="700" fill="{ACCENT}">The student judges, explains, and refines by hand</text>
  <rect class="bar" x="60" y="620" width="{create_w}" height="64" rx="10" fill="#9aa1ad"/>
  <rect class="bar" style="animation-delay:0.3s" x="{60 + create_w + 8}" y="620" width="{rest_w - 8}" height="64" rx="10" fill="{ACCENT}"/>
  <text class="num" x="{60 + create_w // 2}" y="663" font-size="30" font-weight="800" fill="#fff" text-anchor="middle">20%</text>
  <text class="num" style="animation-delay:0.3s" x="{60 + create_w + 4 + rest_w // 2}" y="663" font-size="30" font-weight="800" fill="#fff" text-anchor="middle">80%</text>
  <text x="60" y="740" font-size="24" fill="{INK}">If AI can write working code, “does it run?”</text>
  <text x="60" y="776" font-size="24" fill="{INK}">grades the AI, not the student.</text>"""
    flat += flat_panel("Grade the thinking, not the output", [
        "Let AI scaffold the first version",
        "Grade testing and explaining it",
        "Make the last step by hand, no AI",
    ])

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(hybrid_document(top, flat, STYLE, "Generated by scripts/visuals/create_first.py. One 6s loop."))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
