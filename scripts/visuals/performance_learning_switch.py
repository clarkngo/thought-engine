"""Third visual for the article "Performance Is Not Learning" (2026-11-13): giant numbers and a switch. Writes visual-switch.svg.

Layout: one giant number per measurement, from one trial (Bastani et al., PNAS 2025). A pixel switch flips the AI
off halfway through the loop: the robot vanishes, and the exam number (-17%) lights up under the practice number
(+48%). No takeaway panel.
"""
from pathlib import Path

from handoff import ROBOT
from pixel import ACCENT, ALERT, INK, document, sprite, title

OUT = Path(__file__).resolve().parents[2] / "content/articles/2026-11-13-performance-is-not-learning/visual-switch.svg"
GRAY = "#5d6470"
STEEL = "#9aa1ad"
SW_X, SW_Y, SW_W, SW_H = 60, 548, 176, 64

STYLE = f"""    .on {{ animation: on 6s steps(1) infinite; }}
    @keyframes on {{ 0% {{ opacity: 1; }} 50% {{ opacity: 0; }} }}
    .off {{ animation: off 6s steps(1) infinite; }}
    @keyframes off {{ 0% {{ opacity: 0; }} 50% {{ opacity: 1; }} }}
    .dim {{ animation: dim 6s steps(1) infinite; }}
    @keyframes dim {{ 0% {{ opacity: 0.12; }} 50% {{ opacity: 1; }} }}
    .knob {{ animation: knob 6s steps(1) infinite; }}
    @keyframes knob {{ 0% {{ transform: translateX({SW_W - SW_H}px); }} 50% {{ transform: translateX(0); }} }}
"""


def main():
    body = title("Same students.", "Switch the AI off.", "Bastani et al., PNAS 2025: ~1,000 high school math students, vs. a no-AI group")

    # Practice: always on screen.
    body += f"""
  <text x="48" y="470" font-size="210" font-weight="800" fill="{ACCENT}" letter-spacing="-8">+48%</text>
  <text x="600" y="358" font-size="24" font-weight="800" fill="{GRAY}" letter-spacing="2">PRACTICE</text>
  <text x="600" y="404" font-size="32" font-weight="800" fill="{INK}">with a ChatGPT-style</text>
  <text x="600" y="446" font-size="32" font-weight="800" fill="{INK}">assistant</text>"""

    # The switch, with the robot beside it while it's on.
    body += f"""
  <path d="M60 {SW_Y + SW_H // 2} H1020" stroke="{STEEL}" stroke-width="4" stroke-dasharray="12 10"/>
  <rect x="{SW_X - 12}" y="{SW_Y - 12}" width="{SW_W + 300}" height="{SW_H + 24}" fill="#f7f5f0"/>
  <rect class="on" x="{SW_X}" y="{SW_Y}" width="{SW_W}" height="{SW_H}" fill="{ACCENT}" stroke="{INK}" stroke-width="4"/>
  <rect class="off" x="{SW_X}" y="{SW_Y}" width="{SW_W}" height="{SW_H}" fill="#e6e3da" stroke="{INK}" stroke-width="4"/>
  <rect class="knob" x="{SW_X + 8}" y="{SW_Y + 8}" width="{SW_H - 16}" height="{SW_H - 16}" fill="#fff" stroke="{INK}" stroke-width="4"/>
  <text class="on" x="{SW_X + SW_W + 24}" y="{SW_Y + 44}" font-size="32" font-weight="800" fill="{ACCENT}">AI on</text>
  <text class="off" x="{SW_X + SW_W + 24}" y="{SW_Y + 44}" font-size="32" font-weight="800" fill="{GRAY}">AI off</text>
  <g class="on">{sprite(ROBOT, 380, SW_Y - 4, 6)}</g>"""

    # Exam: lights up when the AI is off.
    body += f"""
  <g class="dim">
  <text x="48" y="840" font-size="210" font-weight="800" fill="{ALERT}" letter-spacing="-8">−17%</text>
  <text x="600" y="728" font-size="24" font-weight="800" fill="{GRAY}" letter-spacing="2">EXAM</text>
  <text x="600" y="774" font-size="32" font-weight="800" fill="{INK}">same students,</text>
  <text x="600" y="816" font-size="32" font-weight="800" fill="{INK}">assistant removed</text>
  </g>"""

    body += f"""
  <text x="60" y="924" font-size="36" font-weight="800" fill="{INK}">Performance: what students do with help.</text>
  <text x="60" y="972" font-size="36" font-weight="800" fill="{ACCENT}">Learning: what remains without it.</text>
  <text x="60" y="1030" font-size="22" fill="{GRAY}">Both numbers compare the AI group with the no-AI group.</text>"""

    OUT.write_text(document(body, STYLE, "Generated by scripts/visuals/performance_learning_switch.py. One 6s loop."))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
