"""Builder for hybrid stat visuals: pixel people on top, flat grouped bar chart below.

Each post script calls build() with its own data. Bars grow in, hold, and reset on a 6s loop;
speech bubbles pop in pixel-style (steps), bars and numbers move smoothly (linear).
"""
from pathlib import Path
from xml.sax.saxutils import escape

from people import BUBBLE_PX
from pixel import divider, flat_panel, hybrid_document, pixel_card, sprite, title

POSTS = Path(__file__).resolve().parents[2] / "content/posts"
BAR_X, BAR_MAX = 400, 480  # bars span x 400..880; numbers right-aligned at 1020
ROW_GAP, BAR_H = 40, 28

STYLE = """
    .pop { animation: pop 6s steps(1) infinite; }
    @keyframes pop { 0% { opacity: 0; } 10% { opacity: 1; } 94% { opacity: 0; } }
    .bar { transform-box: fill-box; transform-origin: left center; animation: grow 6s linear infinite both; }
    @keyframes grow { 0% { transform: scaleX(0); } 15%, 92% { transform: scaleX(1); } 98%, 100% { transform: scaleX(0); } }
    .num { animation: num 6s linear infinite both; }
    @keyframes num { 0%, 12% { opacity: 0; } 18%, 92% { opacity: 1; } 96%, 100% { opacity: 0; } }
"""


def build(slug, script, lines, cards, section, groups, panel, caption=None, out_name="visual-hybrid.svg",
          bar_x=BAR_X, bar_max=BAR_MAX):
    """
    slug:    post folder name
    lines:   (title line 1, title line 2, subtitle)
    cards:   [(sprite art, label, bubble art or None)], 2 or 3 of them
    section: label for the flat half, e.g. "THE GAP"
    groups:  [{"title": str or None, "max": number, "rows": [(label, value, color, text)]}]
    panel:   (heading, [3 lines])
    bar_x, bar_max: where bars start and their full width (move right for long labels)
    """
    centers = {2: [300, 780], 3: [180, 540, 900]}[len(cards)]
    top = title(*lines)
    for i, (art, label, bubble) in enumerate(cards):
        top += pixel_card(centers[i], escape(label), art, delay=i * 0.2)
        if bubble:
            top += f'\n  <g class="pop">{sprite(bubble, centers[i] + 60, 282, BUBBLE_PX)}</g>'

    flat = divider(escape(section))
    y = 566
    n = 0
    for group in groups:
        if group.get("title"):
            flat += f'\n  <text x="60" y="{y + 14}" font-size="20" font-weight="800" fill="#5d6470" letter-spacing="1">{escape(group["title"])}</text>'
            y += 26
        for label, value, color, text in group["rows"]:
            width = bar_max * value / group["max"]
            delay = n * 0.15
            flat += f"""
  <text x="60" y="{y + 21}" font-size="22" font-weight="700" fill="#1b1d21">{escape(label)}</text>
  <rect class="bar" style="animation-delay:{delay:.2f}s" x="{bar_x}" y="{y}" width="{width:.0f}" height="{BAR_H}" rx="7" fill="{color}"/>
  <text class="num" style="animation-delay:{delay:.2f}s" x="1020" y="{y + 21}" font-size="24" font-weight="800" fill="{color}" text-anchor="end">{escape(text)}</text>"""
            y += ROW_GAP
            n += 1
        y += 12
    if caption:
        flat += f'\n  <text x="60" y="806" font-size="22" fill="#5d6470">{escape(caption)}</text>'
    flat += flat_panel(*panel)

    out = POSTS / slug / out_name
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(hybrid_document(top, flat, STYLE, f"Generated by scripts/visuals/{script}. One 6s loop."))
    print(f"Wrote {out}")
