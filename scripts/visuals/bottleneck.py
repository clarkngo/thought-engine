"""Visual for "The Bottleneck Moved" (2026-11-05): a practice post from Clark's own course build.

Layout: the shape is the idea. A robot drafts crates that race along a conveyor, then pile up at a narrow
"keep it consistent" gate where an instructor checks them one at a time. Below, three copies of the course
disagree (the real drift: Week 7 vs 8, 50 vs 40 points). No takeaway panel.
"""
from pathlib import Path

from handoff import CRATE, ROBOT
from people import BUBBLE_PX, CHECK, PROFESSOR
from pixel import ACCENT, ALERT, INK, SUCCESS, document, sprite, title

OUT = Path(__file__).resolve().parents[2] / "content/posts/2026-11-05-the-bottleneck-moved/visual.svg"
GRAY = "#5d6470"
BELT_Y = 470
GATE_X = 690

STYLE = """
    .zip { animation: zip 1.5s steps(5) infinite; }
    @keyframes zip { 0% { transform: translateX(0); } 100% { transform: translateX(250px); } }
""" + "".join(
    f"""    .q{i} {{ animation: q{i} 6s steps(1) infinite; }}
    @keyframes q{i} {{ 0% {{ opacity: 0; }} {10 + i * 16}% {{ opacity: 1; }} 96% {{ opacity: 0; }} }}
"""
    for i in range(5)
) + """
    .drift { animation: drift 6s steps(1) infinite; }
    @keyframes drift { 0% { opacity: 0; } 50% { opacity: 1; } 96% { opacity: 0; } }
"""

# (copy, week, points, drifted)
COPIES = [("Syllabus", "Week 7", "50 pts", False), ("Student site", "Week 8", "40 pts", True), ("LMS", "Week 7", "50 pts", False)]


def main():
    body = title("Drafting got fast.", "The bottleneck moved.", "Building a course with an AI assistant as a build partner")

    # Conveyor: fast drafting on the left, a narrow gate, one-at-a-time checking on the right.
    body += f"""
  <g class="bob">{sprite(ROBOT, 60, BELT_Y - 112)}</g>
  <rect x="170" y="{BELT_Y}" width="850" height="12" fill="{INK}"/>
  <text x="200" y="300" font-size="26" font-weight="800" fill="{SUCCESS}">AI drafts: minutes</text>
  <g class="zip">{sprite(CRATE, 180, BELT_Y - 46, 4)}</g>
  <g class="zip" style="animation-delay:-0.75s">{sprite(CRATE, 180, BELT_Y - 46, 4)}</g>"""
    # The queue piles up before the gate.
    for i in range(5):
        x = GATE_X - 64 - (i % 3) * 56
        y = BELT_Y - 46 - (i // 3) * 46
        body += f'\n  <g class="q{i}">{sprite(CRATE, x, y, 4)}</g>'
    body += f"""
  <rect x="{GATE_X - 4}" y="{BELT_Y - 150}" width="28" height="94" fill="{ALERT}"/>
  <rect x="{GATE_X - 16}" y="{BELT_Y - 150}" width="52" height="12" fill="{ALERT}"/>
  <rect x="{GATE_X - 16}" y="{BELT_Y - 68}" width="52" height="12" fill="{ALERT}"/>
  <text x="{GATE_X + 10}" y="300" font-size="26" font-weight="800" fill="{ALERT}" text-anchor="middle">Keep it consistent</text>
  {sprite(CRATE, GATE_X + 44, BELT_Y - 46, 4)}
  <g class="bob" style="animation-delay:0.3s">{sprite(PROFESSOR, 880, BELT_Y - 112)}</g>
  {sprite(CHECK, 960, BELT_Y - 182, BUBBLE_PX)}
  <text x="900" y="{BELT_Y + 46}" font-size="22" font-weight="700" fill="{GRAY}" text-anchor="middle">one at a time</text>"""

    # Three copies of the same course that drifted apart.
    body += f'\n  <text x="60" y="590" font-size="24" font-weight="800" fill="{GRAY}" letter-spacing="2">THE SAME COURSE, THREE COPIES</text>'
    for i, (name, week, pts, drifted) in enumerate(COPIES):
        x = 60 + i * 322
        color = ALERT if drifted else INK
        body += f"""
  <rect x="{x + 8}" y="618" width="290" height="160" fill="{INK}"/>
  <rect x="{x}" y="610" width="290" height="160" fill="#fff" stroke="{INK}" stroke-width="4"/>
  <text x="{x + 22}" y="652" font-size="26" font-weight="800" fill="{ACCENT}">{name}</text>
  <text x="{x + 22}" y="700" font-size="30" font-weight="700" fill="{INK}">Due: {week}</text>
  <text x="{x + 22}" y="746" font-size="30" font-weight="700" fill="{INK}">Worth: {pts}</text>"""
        if drifted:
            body += f"""
  <g class="drift">
    <rect x="{x + 10}" y="670" width="270" height="88" fill="none" stroke="{ALERT}" stroke-width="6"/>
    <text x="{x + 22}" y="700" font-size="30" font-weight="700" fill="{color}">Due: {week}</text>
    <text x="{x + 22}" y="746" font-size="30" font-weight="700" fill="{color}">Worth: {pts}</text>
  </g>"""

    body += f"""
  <text x="60" y="862" font-size="44" font-weight="800" fill="{INK}">Building is no longer the bottleneck.</text>
  <text x="60" y="920" font-size="44" font-weight="800" fill="{ACCENT}">Deciding and staying consistent are.</text>
  <text x="60" y="1026" font-size="22" fill="{GRAY}">From one course build, Aug–Oct 2026</text>"""

    OUT.write_text(document(body, STYLE, "Generated by scripts/visuals/bottleneck.py. One 6s loop."))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
