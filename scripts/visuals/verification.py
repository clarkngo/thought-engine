"""Visual for "Teach Verification, Not Syntax" (2026-11-04).

Top (pixel): the AI writes the code, the student explains it, the instructor asks why (oral code review).
Bottom (flat): skills losing centrality are struck through, then the skills gaining it appear
(per the 2026 NUS–Google CS education workshop report).
"""
from pathlib import Path

from handoff import ROBOT
from people import BUBBLE_PX, CODE, PROFESSOR, QUESTION, STUDENT
from pixel import ALERT, INK, SUCCESS, divider, flat_panel, hybrid_document, pixel_card, sprite, title

OUT = Path(__file__).resolve().parents[2] / "content/posts/2026-11-02-teach-verification-not-syntax/visual-hybrid.svg"

LESS = ["Implementation-level coding", "Hand debugging and testing", "Writing documentation"]
MORE = ["Verifying AI-generated work", "System design and abstraction", "Critical evaluation"]
ROW_Y = [604, 654, 704]
COL_X = [60, 560]
COL_W = 460

STYLE = """
    .pop { animation: pop 6s steps(1) infinite; }
    @keyframes pop { 0% { opacity: 0; } 8% { opacity: 1; } 94% { opacity: 0; } }
    .pop2 { animation: pop2 6s steps(1) infinite; }
    @keyframes pop2 { 0% { opacity: 0; } 30% { opacity: 1; } 94% { opacity: 0; } }

    .less { animation: less 6s linear infinite; }
    @keyframes less { 0%, 4% { opacity: 0; } 10%, 30% { opacity: 1; } 40%, 92% { opacity: 0.45; } 98%, 100% { opacity: 0; } }
    .strike { transform-box: fill-box; transform-origin: left center; animation: strike 6s linear infinite both; }
    @keyframes strike { 0%, 30% { transform: scaleX(0); } 38%, 92% { transform: scaleX(1); } 98%, 100% { transform: scaleX(0); } }
    .more { animation: more 6s linear infinite both; }
    @keyframes more { 0%, 40% { opacity: 0; transform: translateX(-16px); } 48%, 92% { opacity: 1; transform: translateX(0); } 98%, 100% { opacity: 0; } }
"""


def column(i, items, color, heading, cls):
    x = COL_X[i]
    out = f'\n  <text x="{x}" y="590" font-size="20" font-weight="800" fill="{color}" letter-spacing="2">{heading}</text>'
    for k, item in enumerate(items):
        y = ROW_Y[k]
        delay = f' style="animation-delay:{k * 0.25:.2f}s"' if cls == "more" else ""
        out += f"""
  <g class="{cls}"{delay}>
    <rect x="{x}" y="{y}" width="{COL_W}" height="40" rx="20" fill="#fff" stroke="{color}" stroke-width="2"/>
    <text x="{x + 22}" y="{y + 27}" font-size="22" font-weight="700" fill="{INK}">{item}</text>"""
        if cls == "less":
            out += f'\n    <rect class="strike" x="{x + 16}" y="{y + 18}" width="{COL_W - 32}" height="4" rx="2" fill="{ALERT}"/>'
        out += "\n  </g>"
    return out


def main():
    centers = [180, 540, 900]
    top = title("Teach verification,", "not syntax.", "CS1 with oral code reviews · NUS–Google CS education report, 2026")
    top += pixel_card(centers[0], "AI writes it", ROBOT, 0)
    top += pixel_card(centers[1], "Student explains it", STUDENT, 0.2)
    top += pixel_card(centers[2], "Instructor asks why", PROFESSOR, 0.4, label_size=24)
    top += f'\n  <g class="pop">{sprite(CODE, centers[0] + 60, 282, BUBBLE_PX)}</g>'
    top += f'\n  <g class="pop2">{sprite(QUESTION, centers[2] + 60, 282, BUBBLE_PX)}</g>'

    flat = divider("WHAT TO TEACH NOW")
    flat += column(0, LESS, ALERT, "LESS CENTRAL", "less")
    flat += column(1, MORE, SUCCESS, "MORE CENTRAL", "more")
    flat += '\n  <text x="60" y="796" font-size="22" fill="#5d6470">Weekly oral code reviews: AI use rose, CS1 exam averages held steady</text>'
    flat += flat_panel("Assess the explanation, not the artifact", [
        "Short oral code reviews, every week",
        "Teach verification as a skill",
        "Re-center the fundamentals",
    ])

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(hybrid_document(top, flat, STYLE, "Generated by scripts/visuals/verification.py. One 6s loop."))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
