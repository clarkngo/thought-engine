"""Visual for "AI Replaces What We Teach" (2026-11-09): Stanford Canaries (Aug 2026) + Hosseini & Lichtinger.

Layout: the shape is the idea. A career ladder whose Senior and Mid-level rungs hold, while the Junior rung
is missing (a blinking red outline). A student jumps from the ground and can't reach it. Beside the ladder,
two cards say why: AI complements what the first job taught (tacit) and substitutes for what we teach
(codified). No takeaway panel.
"""
from pathlib import Path

from handoff import ROBOT
from people import PROFESSOR, STUDENT
from pixel import ACCENT, ALERT, INK, SUCCESS, document, sprite, title

OUT = Path(__file__).resolve().parents[2] / "content/posts/2026-11-09-what-the-first-job-taught/visual.svg"
GRAY = "#5d6470"
RAIL_L, RAIL_R = 120, 300  # ladder rails (16 wide)
GROUND = 800
RUNGS = [("Senior", 330), ("Mid-level", 470)]
MISSING_Y = 640

STYLE = """
    .jump { animation: jump 6s steps(1) infinite; }
    @keyframes jump {
      0% { transform: translateY(0); } 20% { transform: translateY(-56px); } 30% { transform: translateY(0); }
      60% { transform: translateY(-56px); } 70% { transform: translateY(0); }
    }
    .gone { animation: gone 1.5s steps(1) infinite; }
    @keyframes gone { 0% { opacity: 1; } 50% { opacity: 0.25; } }
"""


def card(y, kicker, head, color, sub, verdict, art):
    return f"""
  <rect x="528" y="{y + 8}" width="492" height="200" fill="{INK}"/>
  <rect x="520" y="{y}" width="492" height="200" fill="#fff" stroke="{color}" stroke-width="5"/>
  <text x="546" y="{y + 40}" font-size="22" font-weight="800" fill="{GRAY}" letter-spacing="2">{kicker}</text>
  <text x="546" y="{y + 84}" font-size="34" font-weight="800" fill="{color}">{head}</text>
  <text x="546" y="{y + 122}" font-size="22" fill="{INK}">{sub}</text>
  <text x="546" y="{y + 172}" font-size="27" font-weight="800" fill="{INK}">{verdict}</text>
  <g class="bob">{sprite(art, 932, y + 104, 6)}</g>"""


def main():
    body = title("The bottom rung", "is missing.", "Early-career jobs most exposed to AI, Nov 2022 to Jun 2026")

    # Ladder: two rails, two solid rungs, one missing rung, ground line.
    body += f"""
  <rect x="{RAIL_L}" y="290" width="16" height="{GROUND - 290}" fill="{INK}"/>
  <rect x="{RAIL_R}" y="290" width="16" height="{GROUND - 290}" fill="{INK}"/>
  <rect x="60" y="{GROUND}" width="400" height="12" fill="{INK}"/>"""
    for label, y in RUNGS:
        body += f"""
  <rect x="{RAIL_L}" y="{y}" width="{RAIL_R - RAIL_L + 16}" height="16" fill="{INK}"/>
  <text x="{RAIL_R + 32}" y="{y + 16}" font-size="26" font-weight="800" fill="{INK}">{label}</text>"""
    body += f"""
  <rect class="gone" x="{RAIL_L + 16}" y="{MISSING_Y}" width="{RAIL_R - RAIL_L - 16}" height="16" fill="none" stroke="{ALERT}" stroke-width="4" stroke-dasharray="12 8"/>
  <text x="{RAIL_R + 32}" y="{MISSING_Y + 16}" font-size="26" font-weight="800" fill="{ALERT}">Junior</text>
  <text x="{RAIL_R + 32}" y="{MISSING_Y + 48}" font-size="22" font-weight="700" fill="{ALERT}">19% below</text>
  <text x="{RAIL_R + 32}" y="{MISSING_Y + 76}" font-size="22" font-weight="700" fill="{ALERT}">trend</text>
  <g class="jump">{sprite(STUDENT, RAIL_L + 42, GROUND - 96)}</g>"""

    body += card(
        300, "WHAT THE FIRST JOB TAUGHT", "Tacit knowledge", SUCCESS,
        "practice, mentorship, real situations", "AI complements it", PROFESSOR,
    )
    body += card(
        560, "WHAT WE TEACH", "Codified knowledge", ALERT,
        "textbooks, formal procedures", "AI substitutes for it", ROBOT,
    )

    body += f"""
  <text x="60" y="896" font-size="42" font-weight="800" fill="{INK}">AI replaces what we teach.</text>
  <text x="60" y="952" font-size="42" font-weight="800" fill="{ACCENT}">It complements what the first job taught.</text>
  <text x="60" y="1026" font-size="22" fill="{GRAY}">Ages 22–25, most AI-exposed jobs vs. peers. Stanford Digital Economy Lab, Aug 2026</text>"""

    OUT.write_text(document(body, STYLE, "Generated by scripts/visuals/first_job.py. One 6s loop."))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
