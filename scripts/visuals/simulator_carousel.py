"""Carousel for "What Makes a Simulator Train" (2026-11-20): re-angle of the Nov 16-18 simulator series.

Cover, four lessons (one per slide), and a closing question. Writes static slide SVGs into the post's slides/ folder:

    npm run carousel -- content/posts/2026-11-20-what-makes-a-simulator-train
"""
from pathlib import Path

from five_moves import actor, bubble, scene_card, text_lines
from handoff import ROBOT
from people import CHECK, PROFESSOR, STEPS, STUDENT
from pixel import ACCENT, ALERT, INK, document, sprite
from sim_sprites import BOLT, HEART, PLANE, SIM

OUT = Path(__file__).resolve().parents[2] / "content/posts/2026-11-20-what-makes-a-simulator-train/slides"
GRAY = "#5d6470"
TOTAL = 6


def footer(n):
    dots = "".join(
        f'<rect x="{60 + i * 34}" y="1000" width="22" height="22" fill="{ACCENT if i == n else "#d8d4c9"}"/>'
        for i in range(TOTAL)
    )
    arrow = f'<text x="1020" y="1020" font-size="30" font-weight="800" fill="{ACCENT}" text-anchor="end">→</text>' if n < TOTAL - 1 else ""
    return f"""
  {dots}
  <text x="{1020 if n == TOTAL - 1 else 970}" y="1019" font-size="24" font-weight="700" fill="{GRAY}" text-anchor="end">Clark Ngo</text>
  {arrow}"""


# (title lines, scene, evidence lines, source)
LESSONS = [
    (["Feedback,", "not just reps."],
     actor(STUDENT, 190) + bubble(CHECK, 330) + actor(ROBOT, 650),
     ["Counselors who practiced with an AI patient alone", "got less empathetic. With AI feedback added,", "their core skills improved."],
     "Louie et al., CHI 2026 (Stanford), 94 novice counselors"),
    (["Rehearse the", "hard moment."],
     actor(STUDENT, 190) + sprite(HEART, 330, 370, 9) + actor(ROBOT, 650) + sprite(BOLT, 800, 360, 9),
     ["After practicing a conflict with an AI opponent:", "67% fewer escalating tactics than a lecture group,", "and twice the cooperative ones."],
     "Shaikh et al., CHI 2024 (Stanford), 40 participants"),
    (["Then a", "check pilot."],
     sprite(SIM, 150, 420, 12) + sprite(PLANE, 520, 450, 10) + actor(PROFESSOR, 720),
     ["After the simulator, airline pilots still fly", "real flights with a check pilot beside them.", "The rules don't let the simulator replace it."],
     "14 CFR 121.434 and Appendix H to Part 121"),
    (["Measure the skill,", "not the hours."],
     actor(STUDENT, 190) + bubble(STEPS, 330) + actor(PROFESSOR, 650) + bubble(CHECK, 790),
     ["Score what someone can do afterward,", "without the simulator. Hours inside it", "are not a learning outcome."],
     "Design recommendation drawn from the studies above"),
]


def cover():
    return f"""
  <rect x="60" y="120" width="16" height="250" fill="{ACCENT}"/>
  <text x="100" y="196" font-size="84" font-weight="800" fill="{INK}">A simulator</text>
  <text x="100" y="284" font-size="84" font-weight="800" fill="{INK}">is not a</text>
  <text x="100" y="372" font-size="84" font-weight="800" fill="{ACCENT}">training program.</text>
  {actor(STUDENT, 300, 470)}{bubble(STEPS, 440, 390)}
  {actor(ROBOT, 640, 470)}{sprite(BOLT, 800, 400, 9)}""" + text_lines(
        ["AI can now play the patient, the client,", "the customer, the opposing counsel."], 720, 40, INK, 700
    ) + text_lines(["Four things turn practice into skill."], 840, 40, ACCENT, 800)


def lesson(i):
    title_lines, scene, evidence, source = LESSONS[i]
    return (
        f'\n  <text x="60" y="96" font-size="24" font-weight="800" fill="{GRAY}" letter-spacing="2">{i + 1} OF 4</text>'
        + text_lines(title_lines, 176, 72, ACCENT, 800, 84)
        + scene_card(scene)
        + text_lines(evidence, 722, 34, INK, 600, 46)
        + f'\n  <text x="60" y="934" font-size="24" fill="{GRAY}">{source}</text>'
    )


def closing():
    return (
        text_lines(["Who plays", "the coach?"], 220, 110, ACCENT, 800, 124)
        + text_lines(["AI can play the patient, the client,", "and the customer."], 470, 44, INK, 700, 58)
        + text_lines(["Should the feedback come from", "the AI, the instructor, or both?"], 650, 46, INK, 800, 62)
        + f'\n  <text x="60" y="934" font-size="24" fill="{GRAY}">Tell me in the comments.</text>'
    )


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    slides = [cover()] + [lesson(i) for i in range(4)] + [closing()]
    for n, body in enumerate(slides):
        path = OUT / f"slide-{n + 1}.svg"
        path.write_text(document(body + footer(n), "", "Generated by scripts/visuals/simulator_carousel.py."))
        print(f"Wrote {path}")


if __name__ == "__main__":
    main()
