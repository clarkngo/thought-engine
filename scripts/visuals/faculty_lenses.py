"""Visual for "Faculty Are Most Confident Where Students Are Least" (2026-11-11): DEC Global Survey 2026.

Layout: a scene. One course in the middle; a professor on the left asks "Is it still true?", a student on the
right asks "Will it help me do the work?". The bubbles take turns on the loop. Each side keeps its own number
(they answer different survey questions, so there is no shared bar scale). No takeaway panel.
"""
from pathlib import Path

from people import CHECK, PROFESSOR, QUESTION, STUDENT
from pixel import ACCENT, ALERT, INK, SUCCESS, document, sprite, title

OUT = Path(__file__).resolve().parents[2] / "content/posts/2026-11-11-faculty-confident-students-not/visual.svg"
GRAY = "#5d6470"

STYLE = """
    .a { animation: a 6s steps(1) infinite; }
    @keyframes a { 0% { opacity: 1; } 50% { opacity: 0.25; } }
    .b { animation: b 6s steps(1) infinite; }
    @keyframes b { 0% { opacity: 0.25; } 50% { opacity: 1; } }
"""


def bubble(cls, x, lines, color, icon):
    text = "".join(
        f'<text x="{x + 24}" y="{318 + i * 36}" font-size="28" font-weight="800" fill="{INK}">{line}</text>'
        for i, line in enumerate(lines)
    )
    return f"""
  <g class="{cls}">
    <rect x="{x + 8}" y="{280 + 8}" width="300" height="{40 + 36 * len(lines)}" fill="{color}"/>
    <rect x="{x}" y="280" width="300" height="{40 + 36 * len(lines)}" fill="#fff" stroke="{INK}" stroke-width="4"/>
    {text}
    {sprite(icon, x + 236, 280 - 30, 5)}
  </g>"""


def main():
    body = title("Same course.", "Two different questions.", "Digital Education Council Global Survey 2026 · US &amp; Canada")

    # The course, in the middle.
    body += f"""
  <rect x="418" y="338" width="244" height="232" fill="{INK}"/>
  <rect x="410" y="330" width="244" height="232" fill="#fff" stroke="{INK}" stroke-width="4"/>
  <rect x="414" y="334" width="236" height="52" fill="{ACCENT}"/>
  <text x="532" y="370" font-size="26" font-weight="800" fill="#fff" text-anchor="middle">The course</text>"""
    for i, w in enumerate([180, 140, 170, 120]):
        body += f'\n  <rect x="440" y="{414 + i * 34}" width="{w}" height="12" fill="#c9ccd3"/>'

    # Two viewers, two questions.
    body += f"""
  <g class="bob">{sprite(PROFESSOR, 150, 450, 10)}</g>
  <g class="bob" style="animation-delay:-0.3s">{sprite(STUDENT, 810, 450, 10)}</g>"""
    body += bubble("a", 60, ["Is it still true?"], SUCCESS, CHECK)
    body += bubble("b", 720, ["Will it help me", "do the work?"], ALERT, QUESTION)

    # Each side's own number.
    body += f"""
  <text x="60" y="720" font-size="110" font-weight="800" fill="{ACCENT}" letter-spacing="-4">58%</text>
  <text x="60" y="760" font-size="24" fill="{INK}">of faculty aren't worried their</text>
  <text x="60" y="790" font-size="24" fill="{INK}">teaching will go out of date</text>
  <text x="1020" y="720" font-size="110" font-weight="800" fill="{ALERT}" letter-spacing="-4" text-anchor="end">19%</text>
  <text x="1020" y="760" font-size="24" fill="{INK}" text-anchor="end">of students say their program</text>
  <text x="1020" y="790" font-size="24" fill="{INK}" text-anchor="end">feels current for an AI world</text>
  <text x="60" y="884" font-size="40" font-weight="800" fill="{INK}">Faculty grade the content.</text>
  <text x="60" y="938" font-size="40" font-weight="800" fill="{ACCENT}">Students grade the job market.</text>
  <text x="60" y="1026" font-size="22" fill="{GRAY}">Separate survey questions, not a head-to-head comparison.</text>"""

    OUT.write_text(document(body, STYLE, "Generated by scripts/visuals/faculty_lenses.py. One 6s loop."))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
