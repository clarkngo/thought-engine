def sprite(art, ox, oy):
    """Return <rect>s for an ASCII sprite with its top-left at (ox, oy)."""
    rows = [r for r in art.strip("\n").split("\n")]
    out = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            ch = row[x]
            if ch == ".":
                x += 1
                continue
            run = 1  # merge horizontal runs of the same color
            while x + run < len(row) and row[x + run] == ch:
                run += 1
            out.append(
                f'<rect x="{ox + x * PX}" y="{oy + y * PX}" width="{run * PX}" height="{PX}" fill="{PALETTE[ch]}"/>'
            )
            x += run
    return "\n      ".join(out)


def card(cx, label, delay):
    x = cx - 120
